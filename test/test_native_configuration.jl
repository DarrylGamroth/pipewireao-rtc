using Test, PipeWireAORTC

const NE = PipeWireAORTC.InstrumentExport
const ND = PipeWireAORTC.DeploymentConfiguration
const NC = PipeWireAORTC.Common

function native_configuration_input(directory)
    mkpath(joinpath(directory, "rtc"))
    NC.write_json(joinpath(directory, "rtc", "core.conf"), Dict("context.modules" =>
        [Dict("name" => "libpipewire-module-queue", "args" =>
            Dict("node.name" => "scientific-queue", "schema" => Dict("shape" => [2, 3])))]))
    spec = Dict{String,Any}("core" => "shared-runtime/core.conf.in", "client" =>
        Dict("core" => "shared-runtime/client-rtc.conf.in",
            "reconstructor" => "shared-runtime/client-julia.conf.in",
            "wavefront" => "shared-runtime/client-julia.conf.in",
            "analysis" => "shared-runtime/client-analysis.conf.in"))
    profile = Dict("scheduling" => Dict("processes" => Dict(
        "core" => Dict("rt-priority" => 12, "data-loops" =>
            Dict("rtc-data-loop" => [2, 3], "telemetry-loop" => [4])),
        "reconstructor" => Dict("rt-priority" => 17, "data-loops" =>
            Dict("julia-data-loop" => [5, 6])),
        "wavefront" => Dict("rt-priority" => 19, "data-loops" =>
            Dict("julia-data-loop" => [7])))))
    return spec, profile
end

@testset "named process native scheduling" begin
    prefix = get(ENV, "PIPEWIREAO_PREFIX", "/opt/pipewireao")
    templates = Dict(name => read(NE.native_template("shared-runtime/" * name))
        for name in NE.TEMPLATE_FILES)
    mktempdir() do directory
        spec, profile = native_configuration_input(directory)
        scientific = read(joinpath(directory, "rtc", "core.conf"))
        NE.render_templates!(directory, spec, profile, prefix)
        @test spec["client"]["reconstructor"] != spec["client"]["wavefront"]
        for (role, cpus, priority) in (("reconstructor", [5, 6], 17), ("wavefront", [7], 19))
            path = joinpath(directory, spec["client"][role])
            config = ND.decode(path, prefix)
            loop = only(config["context.properties"]["context.data-loops"])
            @test loop["loop.name"] == "julia-data-loop"
            @test loop["thread.affinity"] == cpus
            @test loop["loop.rt-prio"] == priority
            rt = only(filter(item -> item["name"] == "libpipewire-module-rt", config["context.modules"]))
            @test rt["args"]["rt.prio"] == priority
            @test startswith(read(path, String), "# Generated by PipeWireAORTC;")
        end
        corepath = joinpath(directory, spec["core"])
        core = ND.decode(corepath, prefix)
        loops = Dict(loop["loop.name"] => loop for loop in core["context.properties"]["context.data-loops"])
        @test loops["rtc-data-loop"]["thread.affinity"] == [2, 3]
        @test loops["telemetry-loop"]["thread.affinity"] == [4]
        @test all(loop["loop.rt-prio"] == 12 for loop in values(loops))
        template_core = ND.decode(NE.native_template("shared-runtime/core.conf.in"), prefix)
        @test core["context.objects"] == template_core["context.objects"]
        queue = only(filter(item -> item["name"] == "libpipewire-module-queue", core["context.modules"]))
        @test queue["args"]["schema"]["shape"] == [2, 3]
        @test core["context.properties"]["core.name"] == "@REMOTE@"
        @test occursin("\"@REMOTE@\"", read(corepath, String))
        coreclient = ND.decode(joinpath(directory, spec["client"]["core"]), prefix)
        coreloop = only(coreclient["context.properties"]["context.data-loops"])
        @test coreloop["loop.name"] == "rtc-data-loop"
        @test coreloop["thread.affinity"] == [2, 3]
        @test coreloop["loop.rt-prio"] == 12
        @test read(joinpath(directory, "rtc", "core.conf")) == scientific
        analysis = ND.decode(joinpath(directory, spec["client"]["analysis"]), prefix)
        @test analysis == ND.decode(NE.native_template("shared-runtime/client-analysis.conf.in"), prefix)
        @test_throws ArgumentError NE.render_templates!(directory, spec, profile, prefix)
    end
    @test all(read(NE.native_template("shared-runtime/" * name)) == bytes for (name, bytes) in templates)
end

@testset "native loop declarations are exact and paths bounded" begin
    prefix = get(ENV, "PIPEWIREAO_PREFIX", "/opt/pipewireao")
    for mutate in (
            (_, profile) -> delete!(profile["scheduling"]["processes"]["core"]["data-loops"], "telemetry-loop"),
            (spec, _) -> (spec["client"]["core"] = "shared-runtime/client-julia.conf.in"),
            (_, profile) -> (profile["scheduling"]["processes"]["wavefront"]["data-loops"]["extra-loop"] = [7]),
            (spec, _) -> (spec["client"]["../escape"] = "shared-runtime/client-julia.conf.in"),
            (spec, _) -> (spec["client"]["wavefront"] = "../client-julia.conf.in"),
            (spec, _) -> (spec["client"]["undeclared"] = "shared-runtime/client-julia.conf.in"),
        )
        mktempdir() do directory
            spec, profile = native_configuration_input(directory)
            mutate(spec, profile)
            @test_throws ArgumentError NE.render_templates!(directory, spec, profile, prefix)
            @test !ispath(joinpath(directory, "shared-runtime"))
        end
    end
    mktempdir() do directory
        spec, profile = native_configuration_input(directory)
        profile["scheduling"]["processes"]["wavefront"]["data-loops"]["julia-data-loop"] = Int[]
        @test_throws PipeWireAORTC.Placement.PlacementError NE.render_templates!(directory, spec, profile, prefix)
        @test !ispath(joinpath(directory, "shared-runtime"))
    end
end
