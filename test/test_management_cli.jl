using Test, PipeWireAORTC, JSON
const MC = PipeWireAORTC.ManagementCLI

@testset "owner management dispatch without a live session" begin
    mktempdir() do root
        request = Dict(
            "protocol" => "pipewireao.configuration/1",
            "op" => "list",
            "arguments" => Dict("limit" => 5),
            "root" => root,
        )
        reply = MC.respond(JSON.json(request))
        @test reply["ok"]
        @test isempty(reply["result"]["items"])
        for protocol in ("invalid", "pipewireao.management/1", "pipewireao.simulator-settings/1")
            request["protocol"] = protocol
            @test !MC.respond(JSON.json(request))["ok"]
        end
        request["protocol"] = "pipewireao.configuration/1"
        for operation in ("Start", "Stop", "Status", "Reset", "register", "history")
            request["op"] = operation
            @test !MC.respond(JSON.json(request))["ok"]
        end
        @test !MC.respond("{")["ok"]
        @test !MC.respond(repeat(" ", 81921))["ok"]
        input = IOBuffer(JSON.json(merge(request, Dict("op" => "list"))) * "\n")
        output = IOBuffer()
        @test MC.serve(input, output) == 0
        @test JSON.parse(String(take!(output)))["ok"]
    end
end

@testset "owner service installation is explicit and independent of session units" begin
    mktempdir() do root
        prefix = joinpath(root, "native % prefix \$value")
        mkpath(joinpath(prefix, "bin"))
        binary = joinpath(prefix, "bin", "pipewireao-management")
        write(binary, "#!/bin/sh\nexit 0\n")
        chmod(binary, 0o700)
        project = pkgdir(PipeWireAORTC)
        directory = joinpath(root, "units")
        paths = MC.install(
            prefix;
            project,
            unit_directory = directory,
            configuration_root = joinpath(root, "catalog"),
            root = joinpath(root, "receipts"),
        )
        @test Set(keys(paths)) ==
            Set(["pipewireao-management.service", "pipewireao-management.socket"])
        service = read(paths["pipewireao-management.service"], String)
        socket = read(paths["pipewireao-management.socket"], String)
        @test occursin("# Generated by PipeWireAORTC.ManagementCLI.install", service)
        @test occursin("--worker-argv", service)
        @test occursin("--heap-size-hint=256M", service)
        @test occursin("ManagementCLI.serve()", service)
        @test occursin("native %% prefix \$value/bin/pipewireao-management", service)
        @test !occursin("native %% prefix \$\$value/bin/pipewireao-management", service)
        @test occursin("--socket %t/pipewireao/management.sock", service)
        @test occursin("SocketMode=0600", socket)
        @test occursin("DirectoryMode=0700", socket)
        @test occursin("WantedBy=sockets.target", socket)
        @test occursin("KillMode=control-group", service)
        @test !occursin("pipewireao-session@", service)
        @test !occursin("systemctl", service)
        @test all(path -> filemode(path) & 0o077 == 0, values(paths))
        @test_throws ArgumentError MC.install(prefix; project, unit_directory = directory)
        @test read(paths["pipewireao-management.service"], String) == service
        @test_throws ArgumentError MC.unit_texts("relative"; project)
        @test_throws ArgumentError MC.unit_texts(prefix; project = "/invalid\nproject")
    end
end
