using Test, PipeWireAORTC, FITSIO, JSON
const CS = PipeWireAORTC.ConfigurationStore
const CLI = PipeWireAORTC.ConfigurationStoreCLI
const AC = PipeWireAORTC.Artifacts

@testset "full transport cache reuses existing materializations" begin
    mktempdir() do root
        store = CS.Store(root)
        record = CS.register!(store, Float32[1, 2]; label = "Cached", scope = "science")
        FITS(CS.read_artifact(store, record["id"])) do file
            header = read_header(file[1])
            @test header["ORIGIN"] == "PipeWireAORTC"
            @test occursin(
                "COMMENT Generated by PipeWireAORTC from a host array.",
                sprint(show, header),
            )
            @test read(file[1]) == Float32[1, 2]
        end
        materialized = CS.materialize!(store, record["id"])
        cache = joinpath(root, "materialized")
        # The existing original and prepared payload occupy two of 1024 slots.
        for index in 1:1022
            touch(joinpath(cache, "retained-$index"))
        end
        @test CS.materialize!(store, record["id"])["prepared_path"] ==
            materialized["prepared_path"]
        @test_throws ArgumentError CS.materialize!(
            store, record["id"]; storage_order = "column-major"
        )
        @test !isfile(joinpath(dirname(materialized["prepared_path"]), "column-major.bin"))
        fresh = CS.register!(store, Float32[3, 4]; label = "Uncached", scope = "science")
        @test_throws ArgumentError CS.materialize!(store, fresh["id"])
        @test !ispath(joinpath(cache, fresh["id"]))
        @test read(materialized["prepared_path"]) == reinterpret(UInt8, Float32[1, 2])
    end
end

@testset "headless Git catalog" begin
    mktempdir() do root
        store = CS.Store(joinpath(root, "catalog"))
        path = joinpath(root, "gain.fits")
        data = reshape(Float32[1, 2, 3, 4, 5, 6], 2, 3)
        FITS(path, "w") do fits
            write(fits, data)
        end
        original = read(path)
        source = AC.FITSArtifact(path; axes = (1, 2))
        first_record = CS.register!(
            store,
            source,
            Float32,
            (2, 3);
            label = "Gain",
            scope = "science",
            metadata = Dict("z" => 1, "a" => Dict("y" => 2, "x" => 3)),
        )
        duplicate = CS.register!(
            store,
            source,
            Float32,
            (2, 3);
            label = "Gain",
            scope = "science",
            metadata = Dict("a" => Dict("x" => 3, "y" => 2), "z" => 1),
        )
        @test first_record["id"] == duplicate["id"]
        @test first_record["commit_oid"] == duplicate["commit_oid"]
        @test length(CS.list_artifacts(store)["items"]) == 1
        other = CS.register!(
            store,
            source,
            Float32,
            (2, 3);
            label = "Other",
            scope = Dict("graph" => "science"),
        )
        @test other["id"] != first_record["id"]
        @test other["content_oid"] == first_record["content_oid"]
        @test_throws ArgumentError CS.register!(
            store, AC.FITSArtifact(path), Float32, (2, 3); label = "Bad", scope = "science"
        )
        @test_throws DimensionMismatch CS.register!(
            store, source, Float32, (3, 2); label = "Bad", scope = "science"
        )
        @test length(CS.list_artifacts(store)["items"]) == 2
        write(path, "mutated after capture")
        @test CS.read_artifact(store, first_record["id"]) == original
        reopened = CS.Store(store.root)
        @test CS.get_artifact(reopened, first_record["id"])["manifest"]["preparation"]["target_shape"] ==
            [2, 3]
        run(CS.git_command(store.repository, "gc", "--prune=now"))
        @test CS.read_artifact(reopened, first_record["id"]) == original
        @test_throws ArgumentError CS.get_artifact(store, "HEAD")
        @test length(CS.list_artifacts(store; limit = 1)["items"]) == 1
        @test_throws ArgumentError CS.list_artifacts(store; limit = 101)
        request = Dict(
            "protocol" => CS.PROTOCOL,
            "root" => store.root,
            "op" => "get",
            "arguments" => Dict("id" => first_record["id"], "layout" => "column-major"),
        )
        response = CLI.respond(JSON.json(request))
        @test response["ok"]
        @test read(response["result"]["path"]) == original
        @test reinterpret(Float32, read(response["result"]["prepared_path"])) == vec(data)
        row_major = CS.materialize!(store, first_record["id"])
        @test read(row_major["prepared_path"]) ==
            AC.pack(AC.PreparedArtifact(data, Dict{String,Any}()))
        @test CS.materialize!(CS.Store(store.root), first_record["id"])["prepared_path"] ==
            row_major["prepared_path"]
        chmod(row_major["prepared_path"], 0o600)
        write(row_major["prepared_path"], "corrupted cached payload")
        @test_throws ArgumentError CS.materialize!(store, first_record["id"])
        @test read(row_major["prepared_path"], String) == "corrupted cached payload"
        @test !CLI.respond("{")["ok"]
        @test !CLI.respond(
            JSON.json(
                Dict(
                    "protocol" => CS.PROTOCOL, "root" => store.root, "op" => "live-control"
                ),
            ),
        )["ok"]
        input = IOBuffer(
            "{\n" *
            JSON.json(
                Dict("protocol" => CS.PROTOCOL, "root" => store.root, "op" => "list")
            ) *
            "\n",
        )
        output = IOBuffer()
        @test CLI.serve(input, output) == 0
        replies = JSON.parse.(split(String(take!(output)), '\n'; keepempty = false))
        @test !replies[1].ok && replies[2].ok
        # Independently missing loose content objects must be detected at retrieval.
        broken = CS.Store(joinpath(root, "broken"))
        record = CS.register!(broken, data; label = "Generated", scope = "science")
        oid = record["content_oid"]
        rm(joinpath(broken.repository, "objects", oid[1:2], oid[3:end]))
        @test_throws ProcessFailedException CS.get_artifact(broken, record["id"])
        sha256root = joinpath(root, "sha256")
        mkpath(sha256root)
        repo = joinpath(sha256root, "artifacts.git")
        CS.git_read(repo, "init", "--bare", "--quiet", "--object-format=sha256", repo)
        sha256store = CS.Store(sha256root)
        record256 = CS.register!(sha256store, data; label = "SHA256", scope = "science")
        @test record256["object_format"] == "sha256"
        @test length(record256["id"]) == 64
        @test CS.get_artifact(sha256store, record256["id"])["id"] == record256["id"]
    end
end

@testset "catalog creation and legacy operation data preservation" begin
    mktempdir() do root
        store = CS.Store(root)
        tables(store) = CS.database(store) do db
            Set(
                String(row.name) for row in CS.DBInterface.execute(
                    db, "SELECT name FROM sqlite_master WHERE type='table'"
                )
            )
        end
        @test !("operation_events" in tables(store))
        record = CS.register!(store, Float32[1, 2]; label = "Retained", scope = "science")
        legacy_schema = "CREATE TABLE operation_events(sequence INTEGER PRIMARY KEY, session_id TEXT, event TEXT, record BLOB)"
        CS.database(store) do db
            CS.DBInterface.execute(db, legacy_schema)
            CS.DBInterface.execute(
                db,
                "INSERT INTO operation_events VALUES(1,'legacy','requested',?)",
                (UInt8[1, 2, 3],),
            )
        end
        reopened = CS.Store(root)
        CS.database(reopened) do db
            schema = only([
                String(row.sql) for row in CS.DBInterface.execute(
                    db, "SELECT sql FROM sqlite_master WHERE name='operation_events'"
                )
            ])
            @test schema == legacy_schema
            columns = [
                String(row.name) for
                row in CS.DBInterface.execute(db, "PRAGMA table_info(operation_events)")
            ]
            @test columns == ["sequence", "session_id", "event", "record"]
            rows = [
                (
                    Int(row.sequence),
                    String(row.session_id),
                    String(row.event),
                    copy(row.record),
                ) for row in CS.DBInterface.execute(db, "SELECT * FROM operation_events")
            ]
            @test rows == [(1, "legacy", "requested", UInt8[1, 2, 3])]
        end
        @test CS.get_artifact(reopened, record["id"])["id"] == record["id"]
        @test isfile(CS.materialize!(reopened, record["id"])["prepared_path"])
        @test !CLI.respond(
            JSON.json(Dict("protocol" => CS.PROTOCOL, "root" => root, "op" => "history"))
        )["ok"]
    end
end
