# Resolve authored choices once; HIL reads only the portable AOS/HIL product.
import FITSIO
import SHA

function Instruments.export_simulation(
    path::AbstractString,
    destination::AbstractString;
    configuration,
    settings = NamedTuple(),
    simulation_graph = "production",
    chopping = NamedTuple(),
)
    return export_simulation(
        configuration, path, destination; settings, simulation_graph, chopping
    )
end

function export_simulation(configuration::AbstractString, path, destination; kwargs...)
    return export_simulation(
        Instruments.Common.read_yaml(configuration), path, destination; kwargs...
    )
end

function export_simulation(
    configuration::PipeWireHILConfiguration,
    path,
    destination;
    settings,
    simulation_graph,
    chopping,
)
    isempty(chopping) ||
        throw(ArgumentError("lockstep export does not select optical chopping"))
    output = abspath(destination)
    ispath(output) && throw(ArgumentError("simulation export destination already exists"))
    declaration = Instruments.load_simulation(path)
    haskey(declaration.document, "hil") || throw(
        ArgumentError(
            "standalone simulation export currently requires a lockstep HIL graph"
        ),
    )
    configured = Instruments.settings(declaration, settings)
    contracts = configured_wire_contracts(declaration)
    AdaptiveOpticsSimPipeWireHIL.validate_wire_contract(
        configuration.frame_encoding,
        configuration.frame_schema,
        configuration.command_schema,
        configuration.command_scale,
        contracts,
    )
    period_ns = round(Int64, Float64(Float32(declaration.document["frame_period_s"])) * 1e9)
    period_ns > 0 || throw(ArgumentError("simulation period must be positive"))
    mkpath(dirname(output))
    temporary = mktempdir(dirname(output); prefix = ".hil-export-")
    try
        graph = simulation_graph_product(
            declaration, configured, simulation_graph, temporary, "", Val(1)
        )
        manifest = Dict(
            "schema_version" => 1,
            "mode" => "lockstep",
            "graph" => graph,
            "hil" => merge(declaration.document["hil"], Dict("period_ns" => period_ns)),
            "pipewire" => simulation_transport(configuration),
        )
        manifest_path = joinpath(temporary, "simulation.yaml")
        Instruments.Common.write_yaml(
            manifest_path,
            manifest;
            header = "Generated by InstrumentConfiguration.export_simulation; regenerate from the authored simulation and selected PipeWire contract.",
        )
        # Verify the same independent public reader that consumers use, before
        # exposing a completed product. No core, links or runtime are opened.
        prepared = AdaptiveOpticsSimPipeWireHIL.Simulation.prepare(
            AdaptiveOpticsSimPipeWireHIL.Simulation.load(manifest_path)
        )
        for node in prepared.definition.nodes
            validate_sample_period(node.config, declaration.document["frame_period_s"])
        end
        mv(temporary, output)
        return joinpath(output, "simulation.yaml")
    finally
        ispath(temporary) && rm(temporary; recursive = true)
    end
end

function simulation_binding_product(data, directory, relative)
    path = joinpath(directory, relative)
    mkpath(dirname(path))
    FITSIO.FITS(path, "w") do fits
        header = FITSIO.FITSHeader(
            ["ORIGIN", "COMMENT"],
            ["PipeWireAORTC", nothing],
            [
                "",
                "Generated by InstrumentConfiguration.export_simulation; regenerate from authored simulation bindings.",
            ],
        )
        FITSIO.write(fits, simulation_binding_storage(data); header)
    end
    return Dict(
        "path" => relative,
        "sha256" => Instruments.Common.sha256_file(path),
        "shape" => collect(size(data)),
        "eltype" => string(eltype(data)),
    )
end

function simulation_graph_product(
    declaration, configured, selection, directory, relative, version = Val(2)
)
    document = Instruments.graph_document(
        declaration, configured; simulation_graph = selection
    )
    validate_simulation_graph_product(version, document)
    factories = configured_graph_node_types(declaration.directory)
    names = unique!(
        vcat(
            runtime_binding_names(document),
            configuration_binding_names(document, factories),
        ),
    )
    values = prepare_bindings(declaration, configured, names)
    bindings = Dict(
        string(name) => simulation_binding_product(
            getproperty(values, name),
            directory,
            joinpath(relative, "bindings", string(index) * ".fits"),
        ) for (index, name) in enumerate(keys(values))
    )
    assets = simulation_model_products!(document, declaration.directory, directory)
    graph = joinpath(relative, "graph.yaml")
    Instruments.Common.write_yaml(
        joinpath(directory, graph),
        document;
        header = "Generated by InstrumentConfiguration.export_simulation from resolved AOS graph declarations; regenerate from the authored simulation.",
    )
    product = Dict(
        "path" => graph,
        "sha256" => Instruments.Common.sha256_file(joinpath(directory, graph)),
        "bindings" => bindings,
    )
    isempty(assets) || (product["assets"] = assets)
    return product
end

validate_simulation_graph_product(::Val{2}, document) = nothing
function validate_simulation_graph_product(::Val{1}, document)
    any(
        node ->
            node["type"] in ("compiled_optical_paths_f32", "compiled_optical_paths_f64"),
        document["nodes"],
    ) && throw(
        ArgumentError("compiled optical model assets require simulation schema version 2"),
    )
    return nothing
end

function simulation_asset_product(source, destination, directory, digest)
    maximum = Owner.MAX_RETAINED_BYTES
    isfile(source) && filesize(source) <= maximum ||
        throw(ArgumentError("compiled optical asset is missing or exceeds 512 MiB"))
    bytes = open(source) do io
        read(io, maximum + 1)
    end
    length(bytes) <= maximum && bytes2hex(SHA.sha256(bytes)) == digest ||
        throw(ArgumentError("compiled optical asset differs from its declared SHA-256"))
    path = joinpath(directory, destination)
    mkpath(dirname(path))
    write(path, bytes)
    return Dict("path" => destination, "sha256" => digest)
end

function simulation_model_products!(graph, source, directory)
    assets = Dict{String,String}()
    for node in graph["nodes"]
        node["type"] in ("compiled_optical_paths_f32", "compiled_optical_paths_f64") ||
            continue
        config = node["config"]
        original = Instruments.D.relative_asset(source, config["model_path"])
        digest = config["model_sha256"]
        # Copy the generated model and its declared arrays byte for byte. AOS
        # retains parsing/validation and the compiled numerical implementation.
        model = joinpath("models", digest, basename(original))
        simulation_asset_product(original, model, directory, digest)
        assets[model] = digest
        metadata = Instruments.Common.read_yaml(
            joinpath(directory, model); maximum = 4 * 1024 * 1024
        )
        for entry in values(metadata["arrays"])
            original_array = Instruments.D.relative_asset(dirname(original), entry["path"])
            array = joinpath(dirname(model), entry["path"])
            simulation_asset_product(original_array, array, directory, entry["sha256"])
            assets[array] = entry["sha256"]
        end
        config["model_path"] = model
    end
    return [
        Dict("path" => path, "sha256" => assets[path]) for
        path in sort!(collect(keys(assets)))
    ]
end

function export_simulation(
    configuration::AbstractDict, path, destination; settings, simulation_graph, chopping
)
    simulation_graph == "production" ||
        throw(ArgumentError("optical export selects its declared physical paths"))
    Instruments.fields(
        configuration,
        ("schema_version", "mode", "pipewire", "source", "chopping"),
        ("mode", "pipewire"),
        "optical export configuration",
    )
    get(configuration, "schema_version", 2) == 2 ||
        throw(ArgumentError("optical export requires schema version 2"))
    mode = optical_export_mode(configuration["mode"])
    if haskey(configuration, "chopping")
        isempty(chopping) || throw(
            ArgumentError("select chopping once, in configuration or keyword arguments")
        )
        chopping = Instruments._instrument_seal(configuration["chopping"])
    end
    declaration = Instruments.load_simulation(path; validate_optics = false)
    configured = Instruments.settings(declaration, settings)
    selections = optical_export_selections(declaration, chopping)
    add_source_selection!(selections, mode, configuration)
    if any(
        name -> Instruments.graph_requires_proper(
            declaration, configured; simulation_graph = name
        ),
        selections,
    )
        Owner.load_instrument(:Proper)
    end
    # Loading an optional scientific extension creates methods in a newer world.
    return Base.invokelatest(
        export_optical_simulation,
        mode,
        configuration,
        path,
        destination,
        settings,
        chopping,
        selections,
    )
end

optical_export_mode(value) =
    throw(ArgumentError("optical export mode must be external_pupil or clocked_optical"))
optical_export_mode(value::AbstractString) = optical_export_mode(Val(Symbol(value)))
optical_export_mode(mode::Union{Val{:external_pupil},Val{:clocked_optical}}) = mode

function optical_export_selections(declaration, chopping)
    names = Set{String}(keys(declaration.instrument.document["optical_paths"]))
    for entry in values(get(declaration.document, "observations", Dict()))
        push!(names, entry["graph"])
    end
    for entry in values(chopping)
        push!(names, entry.unfringed_graph)
    end
    return names
end

function add_source_selection!(selections, ::Val{:external_pupil}, configuration)
    haskey(configuration, "source") && throw(
        ArgumentError("external pupil configuration must not declare a clocked source")
    )
    return nothing
end
function add_source_selection!(selections, ::Val{:clocked_optical}, configuration)
    haskey(configuration, "source") ||
        throw(ArgumentError("clocked optical configuration requires a source"))
    source = Instruments.fields(
        configuration["source"],
        (
            "graph",
            "command_input",
            "amplitude_binding",
            "pupil_axes",
            "period_ns",
            "command_limit",
            "pacing_period_ns",
        ),
        (
            "graph",
            "command_input",
            "amplitude_binding",
            "pupil_axes",
            "period_ns",
            "command_limit",
            "pacing_period_ns",
        ),
        "clocked source export",
    )
    push!(selections, source["graph"])
    return nothing
end

function export_optical_simulation(
    mode, configuration, path, destination, settings, chopping, selections
)
    output = abspath(destination)
    ispath(output) && throw(ArgumentError("simulation export destination already exists"))
    science = ExternalPupilOwner.prepare(path; settings, chopping)
    declaration, configured = science.declaration, science.configured
    paths = Dict()
    for name in keys(science.plant.graphs)
        sensor = getproperty(science.sensors, name)
        observation = getproperty(science.plant.observations, name)
        entry = Dict(
            "graph" => string(name),
            "exposure_duration_ns" =>
                getproperty(science.plant.exposures, name).duration_ns,
            "output" => string(observation.output),
            "sampling_node" => string(observation.sampling_node),
            "sensor" => Dict("schema" => sensor.schema, "properties" => sensor.properties),
        )
        response = get(observation, :response, nothing)
        if response !== nothing
            entry["response"] = Dict(
                "graph" => declaration.document["observations"][string(name)]["graph"],
                "input" => string(response.input),
                "output" => string(response.output),
                "normalized_to_photon_rate" => response.normalized_to_photon_rate,
                "frame_schema" => response.frame_schema,
                "pixel_sampling_m" => collect(response.pixel_sampling_m),
                "exposure_duration_s" => response.exposure_duration_s,
            )
        end
        if haskey(chopping, name)
            selected = getproperty(chopping, name)
            entry["chopping"] = Dict(
                "graph" => selected.unfringed_graph,
                "initial_phase" => string(selected.initial_phase),
                "trigger_high_is_fringed" => selected.trigger_high_is_fringed,
            )
        end
        paths[string(name)] = entry
    end
    mkpath(dirname(output))
    temporary = mktempdir(dirname(output); prefix = ".hil-export-")
    try
        graphs = Dict(
            name => simulation_graph_product(
                declaration,
                configured,
                name,
                temporary,
                joinpath("graphs", string(index)),
            ) for (index, name) in enumerate(sort!(collect(selections)))
        )
        manifest = Dict(
            "schema_version" => 2,
            "mode" => optical_export_mode_name(mode),
            "graphs" => graphs,
            "optical" => Dict(
                "pupil" => Dict(
                    "schema" => science.pupil.schema,
                    "shape" => collect(science.pupil.shape),
                    "properties" => science.pupil.properties,
                ),
                "paths" => paths,
            ),
            "pipewire" => deepcopy(configuration["pipewire"]),
        )
        add_source_product!(
            manifest, mode, configuration, declaration, configured, temporary
        )
        manifest_path = joinpath(temporary, "simulation.yaml")
        Instruments.Common.write_yaml(
            manifest_path,
            manifest;
            header = "Generated by InstrumentConfiguration.export_simulation; regenerate from authored simulation and selected HIL transport configuration.",
        )
        AdaptiveOpticsSimPipeWireHIL.Simulation.prepare(
            AdaptiveOpticsSimPipeWireHIL.Simulation.load(manifest_path)
        )
        mv(temporary, output)
        return joinpath(output, "simulation.yaml")
    finally
        ispath(temporary) && rm(temporary; recursive = true)
    end
end

optical_export_mode_name(::Val{:external_pupil}) = "external_pupil"
optical_export_mode_name(::Val{:clocked_optical}) = "clocked_optical"
add_source_product!(
    manifest, ::Val{:external_pupil}, configuration, declaration, configured, directory
) = nothing
function add_source_product!(
    manifest, ::Val{:clocked_optical}, configuration, declaration, configured, directory
)
    source = deepcopy(configuration["source"])
    name = pop!(source, "amplitude_binding")
    specs = declaration.document["bindings"]
    haskey(specs, name) ||
        throw(ArgumentError("clocked source amplitude binding is undeclared"))
    amplitude = Instruments.binding_values(declaration, configured, specs[name])
    source["amplitude"] = simulation_binding_product(
        amplitude, directory, joinpath("bindings", "source-amplitude.fits")
    )
    manifest["source"] = source
    return nothing
end

simulation_binding_storage(data::AbstractArray) = data
simulation_binding_storage(data::AbstractArray{Bool}) = UInt8.(data)

simulation_transport_value(value) = value
simulation_transport_value(value::NamedTuple) = Dict(
    string(name) => simulation_transport_value(entry) for (name, entry) in pairs(value)
)

function simulation_transport(configuration::PipeWireHILConfiguration)
    return Dict(
        "remote" => configuration.remote,
        "frame_node_name" => configuration.frame_node_name,
        "command_node_name" => simulation_transport_value(configuration.command_node_name),
        "frame_schema" => configuration.frame_schema,
        "command_schema" => simulation_transport_value(configuration.command_schema),
        "rate" => [configuration.rate.num, configuration.rate.denom],
        "timeout_ns" => configuration.timeout_ns,
        "exposure_duration_ns" => configuration.exposure_duration_ns,
        "frame_encoding" => string(configuration.frame_encoding),
        "command_scale" => simulation_transport_value(configuration.command_scale),
    )
end
