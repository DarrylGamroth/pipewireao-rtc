using Printf
using Statistics
using TOML
using PipeWireAORTC

include("../spiders-fringe-20261117/compare.jl")

function image_planes(directory)
    path = joinpath(directory, "unfringed-means.fits")
    data = PipeWireAORTC.InstrumentConfiguration.FITSIO.FITS(path) do file
        permutedims(read(file[1]), (3, 2, 1))
    end
    @assert size(data) == (221, 221, 3) && all(isfinite, data)
    @assert all(in((0, 1)), view(data, :, :, 3))
    mask = data[:, :, 3] .== 1
    @assert count(mask) == 12_703
    return (; baseline = data[:, :, 1] / peak, closed = data[:, :, 2] / peak, mask)
end

function bank_modes(directory)
    function mode_count(seed)
        record = PipeWireAORTC.Common.read_json(joinpath(directory, "filtered-$seed", "measurement.json"))
        return Int(record["controllable_rank"])
    end
    return only(unique(mode_count.((17, 73))))
end

function report_bank_pair(narrow, wide, seed)
    narrow_dir = joinpath(narrow, "filtered-$seed")
    wide_dir = joinpath(wide, "filtered-$seed")
    smaller, larger = read_pairs.((narrow_dir, wide_dir))
    shared = sort!(collect(intersect(keys(smaller), keys(larger))))
    @assert length(shared) >= 0.90 * 2048
    for (window, range) in [("late", 2049:4096); [("block", i:i+511) for i in 2049:512:4096]]
        frames = filter(i -> iseven(i) && i in range, shared)
        contrast(rows, col) = mean(rows[i][col] for i in frames) / peak
        base_small, on_small = contrast(smaller, 1), contrast(smaller, 2)
        base_large, on_large = contrast(larger, 1), contrast(larger, 2)
        @printf("%d,%s,%d,%d,%d,%.9g,%.9g,%.9g,%.9g,%+.4f,%+.4f,%+.4f\n",
            seed, window, first(range), last(range), length(frames), base_small, on_small, base_large, on_large,
            100 * (on_small / base_small - 1), 100 * (on_large / base_large - 1), 100 * (on_large / on_small - 1))
    end
    images_small, images_large = image_planes.((narrow_dir, wide_dir))
    @assert images_small.mask == images_large.mask
    return (; images_small, images_large)
end

function compare_banks(narrow, wide)
    a, b = bank_modes.((narrow, wide))
    @assert a < b
    println("# Generated by banks.jl from four epochs with matched camera and residual exposure IDs.")
    println("seed,window,first,last,unfringed_pairs,baseline$(a),closed$(a),baseline$(b),closed$(b),change$(a)_pct,change$(b)_pct,closed$(b)_vs$(a)_pct")
    foreach(seed -> report_bank_pair(narrow, wide, seed), (17, 73))
end

if abspath(PROGRAM_FILE) == @__FILE__
    compare_banks(ARGS...)
end
