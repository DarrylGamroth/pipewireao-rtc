using Printf
using Statistics

include("../spiders-fringe-banks-20261117/banks.jl")

function summarize_region(narrow, wide)
    println("# Generated by region.jl from paired unfringed mean images.")
    println("seed,detector_region,pixels,contrast112,contrast_wider,change_pct,pixels_darker")
    for seed in (17, 73)
        a, b = [image_planes(joinpath(dir, "filtered-$seed")) for dir in (narrow, wide)]
        @assert a.mask == b.mask
        # Same detector origin and calibrated plate scale as the comparison figure.
        y, x = (ax .- (first(ax) + last(ax)) / 2 for ax in axes(a.mask))
        radius = hypot.(y, x') / 7.86
        outer = a.mask .& (9 .<= radius .<= 12)
        for (name, pixels) in (("whole_mask", a.mask), ("9_to_12_lambda_D", outer),
                               ("rest_of_mask", a.mask .& .!outer))
            small, large = mean(a.closed[pixels]), mean(b.closed[pixels])
            @printf("%d,%s,%d,%.9g,%.9g,%+.4f,%d\n", seed, name, count(pixels), small, large,
                100 * (large / small - 1), count(b.closed[pixels] .< a.closed[pixels]))
        end
    end
end

summarize_region(ARGS...)
