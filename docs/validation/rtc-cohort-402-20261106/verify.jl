# Validate the registered release cohort in a fresh environment and depot.
# julia --project=CONSUMER verify.jl OUTPUT.toml
using Pkg, TOML, Libdl, Test
using PipeWireAORTC

@testset "registered RTC cohort" begin
    @test VERSION >= v"1.13"
    @test !isfile(joinpath(dirname(Base.active_project()), "LocalPreferences.toml"))
    @test all(depot -> !isfile(joinpath(depot, "artifacts", "Overrides.toml")), DEPOT_PATH)
    @test Base.get_extension(PipeWireAORTC, :PipeWireAORTCGraphExt) === nothing
    @test !any(id -> id.name in ("FilterGraphs", "FilterGraphAlgorithms", "FilterGraphPipeWire", "AdaptiveOpticsSim"), keys(Base.loaded_modules))
end

using PipeWireAO, PipeWireAO_jll
using FilterGraphAlgorithms, FilterGraphs, FilterGraphPipeWire
using AdaptiveOpticsSim, AdaptiveOpticsSimPipeWireHIL, AdaptiveOpticsCalibration

expected = Dict(
    "PipeWireAORTC" => v"0.7.0",
    "PipeWireAO" => v"0.9.2",
    "PipeWireAO_jll" => v"4.0.2+0",
    "FilterGraphAlgorithms" => v"0.12.0",
    "FilterGraphs" => v"0.9.0",
    "FilterGraphPipeWire" => v"0.5.2",
    "AdaptiveOpticsSim" => v"0.3.21",
    "AdaptiveOpticsSimPipeWireHIL" => v"0.5.0",
    "AdaptiveOpticsCalibration" => v"0.17.3",
)
packages = Dict(name => only(filter(dep -> dep.name == name, collect(values(Pkg.dependencies())))) for name in keys(expected))
@testset "immutable packages and artifact libraries" begin
    for (name, dep) in packages
        @test dep.version == expected[name]
        @test dep.is_tracking_registry && !dep.is_tracking_path && !dep.is_tracking_repo
        @test bytes2hex(Pkg.GitTools.tree_hash(dep.source)) == string(dep.tree_hash)
    end
    @test PipeWireAO.library_version() == v"4.0.2"
    artifact = String(PipeWireAO_jll.artifact_dir)
    @test bytes2hex(Pkg.GitTools.tree_hash(artifact)) == basename(artifact)
    for product in (:libpipewire_ao, :libspa_ao, :libspa_support)
        path = realpath(getproperty(PipeWireAO_jll, product))
        @test startswith(path, realpath(artifact) * "/")
        handle = Libdl.dlopen(path)
        Libdl.dlclose(handle)
    end
    @test realpath(Libdl.dlpath(PipeWireAO_jll.libpipewire_ao)) == realpath(joinpath(artifact, "lib", "libpipewire-ao-0.3.so"))
    handle = Libdl.dlopen(PipeWireAO_jll.libpipewire_ao)
    try
        accessor = Libdl.dlsym(handle, :pw_ndarray_filter_get_loop)
        @test ccall(accessor, Ptr{Cvoid}, (Ptr{Cvoid},), C_NULL) == C_NULL
    finally
        Libdl.dlclose(handle)
    end
    for extension in (:PipeWireAORTCGraphExt, :PipeWireAORTCCalibrationExt, :PipeWireAORTCOpticsExt, :PipeWireAORTCAOSExt, :PipeWireAORTCOffsetsExt)
        @test Base.get_extension(PipeWireAORTC, extension) !== nothing
    end
    @test !any(id -> id.name in ("JuliaFilterGraph", "FilterGraphIsland"), keys(Base.loaded_modules))
end

length(ARGS) == 1 || error("usage: verify.jl OUTPUT.toml")
receipt = Dict(
    "julia" => string(VERSION),
    "artifact" => String(PipeWireAO_jll.artifact_dir),
    "packages" => Dict(name => Dict("version" => string(dep.version), "tree" => string(dep.tree_hash), "source" => dep.source) for (name, dep) in packages),
)
open(only(ARGS), "w") do io
    println(io, "# Generated by docs/validation/rtc-cohort-402-20261106/verify.jl; rerun in the registered consumer environment.")
    TOML.print(io, receipt; sorted=true)
end
