using PipeWireAORTC, FilterGraphAlgorithms, FilterGraphIsland, FilterGraphPipeWire, JuliaFilterGraph, JSON, Test
const E=PipeWireAORTC.InstrumentExport
const IC=PipeWireAORTC.InstrumentConfiguration
const C=PipeWireAORTC.Common
const prefix=get(ENV,"PIPEWIREAO_PREFIX","/opt/pipewireao")
root=only(ARGS)
@testset "real instrument GUI reference preparation" begin
    for name in ("revolt-classic","gpi2")
        application=joinpath(root,name)
        instrument_path=joinpath(application,"instrument.json")
        metadata_hash=C.sha256_file(instrument_path)
        authoring=E.source_application(application)
        declarations=authoring["graph-configurations"]
        rtc=IC.load_rtc(joinpath(application,get(authoring,"configuration","rtc/configuration.yaml")))
        kwargs=(;dimensions=rtc.document["dimensions"],mirror_controls=rtc.controls["deformable_mirrors"],calibration=rtc.calibration)
        path=joinpath(application,"gui","operator-views.yaml")
        gui=C.read_yaml(path)
        roots=Set{String}()
        E.reference_roots!(roots,gui)
        @test roots ⊆ Set(("schemas","instrument","graphs"))
        E.prepare_graph_configurations!(application,declarations,"instrument.json",prefix;kwargs...)
        context=E.graph_context(JSON.parsefile(instrument_path);kwargs...)
        context["graphs"]=E.graph_contract_context(application,declarations,prefix)
        resolved=C.configuration_value(gui,context)
        @test Set(keys(resolved)) == Set(keys(gui))
        E.write_configuration(path,"yaml",resolved;
            header="Generated by PipeWireAORTC from instrument metadata and prepared graph contracts; do not edit.")
        remaining=Set{String}()
        E.reference_roots!(remaining,C.read_yaml(path))
        @test isempty(remaining)
        @test C.sha256_file(instrument_path) == metadata_hash
        println("GUI ",path," sha256=",C.sha256_file(path))
        println("UNCHANGED INSTRUMENT ",instrument_path," sha256=",metadata_hash)
    end
end
