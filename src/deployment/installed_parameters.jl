parameter_control_instance(invocation) = string(parse(Int64, graph_bootstrap_instance(invocation)) + 1)

function bind_parameter_service!(arguments)
    invocation = ENV["INVOCATION_ID"]
    append!(arguments, ["--bootstrap-instance", graph_bootstrap_instance(invocation),
        "--control-instance", parameter_control_instance(invocation)])
    return nothing
end

# Keep an artifact override in the installation only for a separately selected SDK.
function installed_owner_depot!(prefix, paths, spec, directory)
    depot = get(ENV, "JULIA_DEPOT_PATH", joinpath(homedir(), ".julia") * ":")
    prepare_julia_overlay!((; prefix), paths, spec, directory)
    overlay = joinpath(directory, "julia-depot")
    overrides = joinpath(overlay, "artifacts", "Overrides.toml")
    return isfile(overrides) ? (overlay * ":" * depot, [overrides]) : (depot, String[])
end

function support_unit_name(role, profile, package)
    installation = first(bytes2hex(sha256(realpath(package))), 12)
    return "pipewireao-$role-$profile-$installation@.service"
end

function install_direct_parameters!(package, prefix, project, spec, session, external, julia)
    sources = filter(source -> get(source, "factory", nothing) == "pipewireao.runtime-parameter",
        session["sources"])
    isempty(sources) && return nothing
    any(owner -> owner["role"] == "parameters", spec["owners"]) &&
        fail("parameter transport role conflicts with a declared owner")
    runtime = joinpath(package, "systemd")
    directory = joinpath(runtime, "parameters")
    bindings = Dict("PACKAGE" => package, "PREFIX" => prefix, "RUNTIME" => runtime,
        "REMOTE" => external.socket)
    config = write_parameter_config!(directory, package, spec, session, D.session_links(session),
        bindings, sources)
    placement = deepcopy(spec["placement"]["session"])
    push!(placement["threads"], Dict("cpus" => [placement["leader-cpu"]], "policy" => "other",
        "priority" => 0, "name" => "rtc-bootstrap", "count" => 1))
    bootstrap = "pipewireao.rtc.bootstrap.parameters"
    control = "pipewireao.rtc.parameters." * spec["name"]
    owner = Dict("role" => "parameters", "bootstrap-node" => bootstrap,
        "bootstrap-protocol" => "pipewireao.rtc.owner-bootstrap/1", "control-node" => control,
        "control-protocol" => "pipewireao.rtc.parameter-source/1")
    argv = [julia, "--startup-file=no", "--threads=2,0", "--project=$project", "-e",
        "using PipeWireAORTC; PipeWireAORTC.SessionLaunch.bind_parameter_service!(ARGS); PipeWireAORTC.ParameterSource.main(ARGS)",
        "--", "--config", config, "--remote", external.socket, "--bootstrap-node", bootstrap,
        "--control-node", control]
    paths = D.installed_paths(prefix)
    env = owner_environment(paths, spec, bindings, runtime, "parameters"; ambient = Dict{String,String}())
    depot, overrides = installed_owner_depot!(prefix, paths, spec, directory)
    env["JULIA_DEPOT_PATH"] = depot
    files = [config; joinpath(directory, "client.conf"); overrides]
    env["JULIA_LOAD_PATH"] = "@:@stdlib"
    env["PIPEWIREAO_PREFIX"] = prefix
    env["OPENBLAS_NUM_THREADS"] = "1"
    template = support_unit_name("parameters", spec["name"], package)
    path = joinpath(runtime, template)
    text = S.owner_service_unit("parameters", argv, env, directory, placement;
        requisite = [external.core], after = [external.core])
    text = replace(text, "[Unit]\n" => "[Unit]\nPartOf=pipewireao-session@%i.service\nStopWhenUnneeded=yes\n"; count = 1)
    write(path, "# Generated by PipeWireAORTC.SessionInstall. Reinstall to change this unit.\n" * text)
    push!(files, path)
    service = Dict("fragment" => path, "sha256" => C.sha256_file(path),
        "argv" => argv, "environment" => env,
        "pipewire-library" => realpath(joinpath(paths["library"], "libpipewire-ao-0.3.so")))
    return (; unit = replace(template, "@." => "@%i."), owner, placement, files, service)
end
