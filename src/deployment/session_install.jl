const RTC_RUNTIME_UNIT_PATH = "%t/pipewireao-session-%i"

escape_unit_specifiers(value) = replace(String(value), "%" => "%%")

"Generate a one-shot client launcher bound to the installed application environment."
function installed_launcher(
    julia::AbstractString; environment::AbstractString, commit = nothing,
    legacy::Bool = false, minimal_prepare::Bool = true, historical_publish::Bool = false,
    installed_cache::Bool = false,
)
    pin = commit === nothing ? "" : "export PIPEWIREAO_RTC_EXPORT_COMMIT=$commit\n"
    service_hooks = if installed_cache
        entrypoint = "Base.exit_on_sigint(false); using PipeWireAORTC; exit(PipeWireAORTC.SessionCLI.main(ARGS))"
        argv = ScienceExport.rtc_command(julia, environment; installed_cache, entrypoint)
        "    stop|cleanup) exec " * join(D.shell_quote.(argv), " ") * " \"\$@\" ;;\n"
    else
        ""
    end
    exec_julia = "exec $(D.shell_quote(julia)) --startup-file=no --project=" *
                D.shell_quote(environment)
    entry = " -e 'Base.exit_on_sigint(false); using PipeWireAORTC; exit(PipeWireAORTC.SessionCLI.main(ARGS))' -- \"\$@\""
    startup = if legacy
        ""
    else
        rules = if minimal_prepare
            prepare = "    prepare) $exec_julia -O0 --compile=min$entry ;;\n"
            historical_publish ? prepare * "    publish) $exec_julia -O0$entry ;;\n" : prepare
        elseif historical_publish
            "    prepare|publish) $exec_julia -O0$entry ;;\n"
        else
            "    prepare) $exec_julia -O0$entry ;;\n"
        end
        "case \"\${1-}\" in\n" * service_hooks * rules * "esac\n"
    end
    return "#!/bin/sh\n" *
           "# Generated by PipeWireAORTC.SessionInstall.install; reinstall to change its environment.\n" *
           pin * startup * exec_julia * entry * "\n"
end

_installed_source_owner(value) =
    throw(ArgumentError("new session install requires a declared source owner"))
_installed_source_owner(::String) = nothing
_installed_session_cpu(cpu) =
    throw(ArgumentError("RTC CPU placement must exclude CPU 0 and 1"))
_installed_session_cpu(cpu::Int) =
    cpu >= 2 || throw(ArgumentError("RTC CPU placement must exclude CPU 0 and 1"))

function session_spec(package, prefix)
    spec = D.profile(joinpath(package, "deployment.conf"), prefix)
    spec["cpu-latency-us"] === nothing || throw(
        ArgumentError(
            "headless RTC session does not yet retain a CPU DMA latency lease; cpu-latency-us must be null",
        ),
    )
    _installed_source_owner(get(spec, "source-owner", nothing))
    haskey(spec, "node-owners") || throw(
        ArgumentError("new session install requires exact node-owners in deployment.conf"),
    )
    haskey(spec, "session-runtime") ||
        throw(ArgumentError("new session install requires a packaged Julia RTC launcher"))
    placement = spec["placement"]["session"]
    foreach(_installed_session_cpu, placement["cpus"])
    return spec
end

function session_assets(spec, package, prefix)
    PipeWireAORTC.ScienceExport.validate_rtc(joinpath(package, "rtc"))
    binary = D.session_executable(spec, package, prefix)
    isfile(binary) && !islink(binary) && (stat(binary).mode & 0o111) != 0 ||
        throw(ArgumentError("headless RTC Julia launcher is unavailable: $binary"))
    read(binary, String) == PipeWireAORTC.ScienceExport.rtc_launcher() || throw(
        ArgumentError(
            "headless RTC launcher differs from the selected Julia session policy: $binary",
        ),
    )
    return nothing
end

function external_owner_bindings(entries)
    launch = PipeWireAORTC.SessionLaunch
    owners = Dict{String,String}()
    for entry in entries
        fields = split(entry, '='; limit = 2)
        length(fields) == 2 && occursin(launch.S.ROLE, first(fields)) ||
            throw(ArgumentError("--external-owner requires role=unit.service"))
        role, unit = String.(fields)
        !haskey(owners, role) || throw(ArgumentError("duplicate external owner role $role"))
        !startswith(unit, "pipewireao-graph-") ||
            throw(ArgumentError("select generated graph units with --graph-installation"))
        owners[role] = launch.external_unit(unit)
    end
    return owners
end

function validate_external_owner_roles(spec, external_owners)
    owners = PipeWireAORTC.SessionConfiguration.owner_specs(spec)
    for role in keys(external_owners)
        haskey(owners, role) && role != spec["source-owner"] &&
            D.uses_bootstrap_protocol(owners[role]) && !haskey(owners[role], "control-protocol") ||
            throw(ArgumentError("external owner $role requires a declared persistent bootstrap role"))
    end
    return nothing
end

function install_direct!(
    package, prefix, julia, project, spec, external, external_owners, graphs;
    generated_graphs, explicit = false,
)
    launch = PipeWireAORTC.SessionLaunch
    source_role = spec["source-owner"]
    owners = PipeWireAORTC.SessionConfiguration.owner_specs(spec)
    graph_units = graphs === nothing ? Dict{String,String}() : graphs.owners
    conflicts = intersect(keys(external_owners), keys(graph_units))
    isempty(conflicts) ||
        throw(ArgumentError("external owner roles already have selected graph units: $(join(sort!(collect(conflicts)), ", "))"))
    services = merge(Dict("core" => external.core, source_role => external.source),
        graph_units, external_owners)
    length(unique(values(services))) == length(services) ||
        throw(ArgumentError("direct RTC owner roles require distinct services"))
    all(haskey(services, role) for role in keys(owners)) || return nothing
    all(role in ("fgn", "parameters") || haskey(services, role) for role in
        values(spec["node-owners"])) ||
        throw(ArgumentError("missing service for a directly attached node"))
    # Native FGN modules still need the invocation-owned host.
    "fgn" in values(spec["node-owners"]) && return nothing
    launch.external_source!(spec, deepcopy(owners[source_role]))

    systemd = joinpath(package, "systemd")
    config = joinpath(systemd, "rtc.conf")
    !(ispath(config) || islink(config)) || throw(ArgumentError("reserved RTC configuration: $config"))
    remote = external.socket
    !isempty(basename(remote)) && ncodeunits(remote) <= 100 ||
        throw(ArgumentError("private core socket path exceeds the Unix socket bound or has no name"))
    bindings = Dict("PACKAGE" => package, "PREFIX" => prefix, "REMOTE" => remote)
    source = D.relative_asset(package, spec["session"])
    topology = replace(read(source, String), "@RUNTIME@/@REMOTE@" => "@REMOTE@")
    if occursin("@RUNTIME@", topology)
        explicit && throw(ArgumentError("RTC topology requires invocation-dependent runtime paths"))
        return nothing
    end
    rendered = D.substitute(topology, bindings; quoted = true)
    session = mktemp() do path, io
        write(io, rendered)
        close(io)
        D.decode(path, prefix)
    end
    links = D.validate_session_links(session)
    isempty(links) && throw(ArgumentError("native session requires at least one declared connection"))
    D.validate_execution_groups(session, links)
    configuration = PipeWireAORTC.SessionConfiguration.runtime_configuration(
        remote, Dict("session" => session),
    )
    PipeWireAORTC.ScienceExport.write_spa_config(config, configuration)

    wants = generated_graphs ? copy(graphs.units) : String[]
    requisite = setdiff(collect(values(services)), wants)
    parameters = launch.install_direct_parameters!(package, prefix, project, spec, session, external, julia)
    if parameters !== nothing
        services["parameters"] = parameters.unit
        push!(wants, parameters.unit)
    end
    analysis = install_direct_analysis!(package, prefix, julia, project, spec, external)
    append!(wants, analysis.units)
    files = [config; analysis.files]
    parameters === nothing || append!(files, parameters.files)
    # Escape literal specifiers first, then substitute the two unit specifiers
    # that systemd resolves for the stable RTC runtime directory.
    unit_bindings = Dict(key => escape_unit_specifiers(value) for (key, value) in bindings)
    unit_bindings["RUNTIME"] = RTC_RUNTIME_UNIT_PATH
    environment = Dict{String,String}()
    for (key, value) in spec["session-runtime"]["environment"]
        resolved = D.substitute(escape_unit_specifiers(value), unit_bindings)
        occursin(r"^[A-Za-z_][A-Za-z0-9_]*$", key) && !occursin(r"[\n\r\0]", resolved) ||
            throw(ArgumentError("invalid RTC environment declaration: $key"))
        environment[key] = resolved
    end
    return (; config, configuration, services, socket = remote, graphs, parameters, wants, requisite, environment, files)
end

function install_direct_analysis!(package, prefix, julia, project, spec, external)
    launch = PipeWireAORTC.SessionLaunch
    entries = get(spec, "analysis", [])
    isempty(entries) && return (; units = String[], files = String[])
    paths = D.installed_paths(prefix)
    systemd = joinpath(package, "systemd")
    directory = mkdir(joinpath(systemd, "analysis"); mode = 0o700)
    client = D.relative_asset(package, spec["client"]["analysis"])
    bindings = Dict(
        "PACKAGE" => package, "PREFIX" => prefix, "RUNTIME" => directory, "REMOTE" => external.socket,
    )
    rendered = D.substitute(read(client, String), bindings; quoted = true)
    units = String[]
    depot, files = launch.installed_owner_depot!(prefix, paths, spec, directory)
    for entry in entries
        role = "analysis-" * entry["name"]
        config_dir = mkdir(joinpath(directory, role); mode = 0o700)
        config_path = joinpath(config_dir, "client.conf")
        write(config_path, rendered)
        push!(files, config_path)
        placement = Dict("cpus" => entry["cpus"], "leader-cpu" => first(entry["cpus"]))
        argv = [
            julia, "--startup-file=no", "--project=" * project,
            "-e", "using PipeWireAORTC; exit(PipeWireAORTC.Analysis.main(ARGS))", "--",
            "--config", D.relative_asset(package, entry["config"]), "--remote", external.socket,
        ]
        env = launch.analysis_environment(paths, directory, role, prefix, external.socket)
        env["JULIA_DEPOT_PATH"] = depot
        unit = launch.S.owner_service_unit(
            role, argv, env, package, placement; ordinary = true, stop_signal = "SIGHUP",
        )
        rtc = "pipewireao-session@%i.service"
        unit = replace(unit, "[Unit]\n" => "[Unit]\nAfter=$rtc\nBindsTo=$rtc\nPartOf=$rtc\n"; count = 1)
        name = launch.support_unit_name(role, spec["name"], package)
        path = joinpath(systemd, name)
        !(ispath(path) || islink(path)) || throw(ArgumentError("reserved analysis service: $path"))
        write(path, "# Generated by PipeWireAORTC.SessionInstall. Reinstall to change this unit.\n" * unit)
        push!(units, replace(name, "@." => "@%i."))
        push!(files, path)
    end
    return (; units, files)
end

# Record the installation selected by this unit. Replacements read one bounded
# JSON document and check the installed files before acquiring any owners.
function install_activation!(
    package, prefix, julia, project, launcher, spec, commit;
    sysimage = nothing, validated_image = nothing, direct = nothing, installed_cache = false,
)
    launch = PipeWireAORTC.SessionLaunch
    path = joinpath(package, "systemd", launch.ACTIVATION_FILE)
    !(ispath(path) || islink(path)) || throw(ArgumentError("reserved activation file: $path"))
    paths = D.installed_paths(prefix)
    tracked = GitExport.verified_paths(package)
    names = Set{String}([keys(spec["artifacts"])...; values(spec["client"])...;
                          spec["core"]; spec["session"]; "deployment.conf"])
    tracked === nothing || union!(names, tracked)
    graphs = launch.graph_templates(package)
    for file in graphs
        relative = joinpath("graphs", file)
        D.relative_asset(package, relative)
        push!(names, relative)
    end
    files = [joinpath(package, name) for name in names]
    append!(files, [julia, joinpath(project, "Project.toml"), joinpath(project, "Manifest.toml"),
                    D.session_executable(spec, package, prefix), launcher, paths["parser"],
                    paths["daemon"], joinpath(paths["library"], "libpipewire-ao-0.3.so")])
    sysimage === nothing || push!(files, sysimage)
    document = Dict(
        "version" => 1, "package" => package, "prefix" => prefix, "launcher" => launcher,
        "project" => project, "julia" => julia, "paths" => paths, "profile" => spec,
        "files" => Dict(file => launch.graph_file_identity(file) for file in unique(files)),
        "export-commit" => commit, "graph-templates" => graphs,
    )
    installed_cache && (document["installed-cache"] = true)
    if direct !== nothing
        document["config"] = direct.config
        document["direct-configuration"] = direct.configuration
        for file in direct.files
            document["files"][file] = launch.graph_file_identity(file)
        end
        document["direct-services"] = direct.services
        document["direct-companions"] = filter(name -> endswith(name, "@%i.service"), direct.wants)
        document["direct-socket"] = direct.socket
        if direct.graphs !== nothing
            document["graph-manifest"] = direct.graphs.manifest
            document["graph-manifest-sha256"] = direct.graphs.digest
        end
        if direct.parameters !== nothing
            document["direct-parameter-owner"] = direct.parameters.owner
            document["direct-parameter-placement"] = direct.parameters.placement
            document["direct-parameter-service"] = direct.parameters.service
        end
    end
    if sysimage !== nothing
        identity = document["files"][sysimage]
        validated_image === nothing || validated_image == identity ||
            throw(ArgumentError("Julia sysimage changed after installation validation"))
        document["julia-sysimage"] = sysimage
        document["julia-sysimage-sha256"] = C.sha256_file(sysimage)
        launch.graph_file_identity(sysimage) == identity ||
            throw(ArgumentError("Julia sysimage changed during activation sealing"))
    end
    C.write_json(path, document; atomic = true)
    filesize(path) <= D.MAX_CONFIG_BYTES || throw(ArgumentError("installed activation exceeds size bound"))
    return (; julia, project, sysimage, digest = C.sha256_file(path))
end

function installed_unit(
    template, spec; launcher, package, prefix, executable, external = nothing,
    persistent = nothing, activation = nothing, direct = nothing,
)
    quote_unit(value) = String(JSON.json(escape_unit_specifiers(value)))
    lines = String[]
    if occursin("@ACTIVATION_ENVIRONMENT@", template)
        activation === nothing && throw(ArgumentError("RTC unit requires its installed activation"))
        launch = PipeWireAORTC.SessionLaunch
        env = Dict(launch.ACTIVATION_ENV => activation.digest, launch.INSTALLATION_ENV => package,
                   "PIPEWIREAORTC_JULIA" => activation.julia, "PIPEWIREAORTC_PROJECT" => activation.project)
        append!(lines, ["Environment=" * quote_unit(key * "=" * env[key]) for key in sort!(collect(keys(env)))])
        if direct !== nothing
            for key in sort!(collect(keys(direct.environment)))
                push!(lines, "Environment=" * String(JSON.json(key * "=" * direct.environment[key])))
            end
        end
    end
    command = quote_unit(executable)
    sysimage = activation === nothing ? nothing : get(activation, :sysimage, nothing)
    installed_cache = occursin(INSTALLED_COMMAND, template)
    if installed_cache || sysimage !== nothing
        installed_cache || occursin("@RTC_COMMAND@", template) ||
            throw(ArgumentError("pinned RTC package does not support a Julia sysimage"))
        arguments = PipeWireAORTC.ScienceExport.rtc_command(
            activation.julia, activation.project; sysimage, installed_cache,
        )
        command = join((quote_unit(replace(argument, "\$" => "\$\$")) for argument in arguments), " ")
    end
    leader = spec["placement"]["session"]["leader-cpu"]
    config = direct === nothing ? "" : quote_unit(replace(direct.config, "\$" => "\$\$"))
    dependencies = String[]
    if direct !== nothing
        ordered = sort!(collect(values(direct.services)))
        push!(dependencies, "After=" * join(ordered, " "))
        isempty(direct.requisite) ||
            push!(dependencies, "Requisite=" * join(sort(direct.requisite), " "))
        isempty(direct.wants) || push!(dependencies, "Wants=" * join(sort(direct.wants), " "))
    end
    unit = replace(
        template,
        "@ACTIVATION_ENVIRONMENT@" => join(lines, "\n"),
        "@LAUNCHER@" => quote_unit(launcher),
        "@PACKAGE@" => quote_unit(package),
        "@PIPEWIRE_PREFIX@" => quote_unit(prefix),
        INSTALLED_COMMAND => command,
        "@RTC_COMMAND@" => command,
        "@RTC_CONFIGURATION@" => config,
        "@DIRECT_DEPENDENCIES@" => join(dependencies, "\n"),
        "@RTC_EXECUTABLE@" => quote_unit(executable),
        "@SOURCE_ROLE@" => spec["source-owner"],
        "@CPUS@" => string(leader),
        "TimeoutStartSec=300" =>
            "TimeoutStartSec=" * string(D.startup_timeout_ms(spec) / 1000),
    )
    occursin(r"@[A-Z_]+@", unit) &&
        throw(ArgumentError("unresolved RTC unit template binding"))
    if external !== nothing
        unit *= "\n[Service]\n"
        for (key, value) in zip(PipeWireAORTC.SessionLaunch.EXTERNAL_SERVICE_ENV, external)
            unit *= "Environment=" * quote_unit(key * "=" * value) * "\n"
        end
    end
    if persistent !== nothing && direct === nothing
        units = join(persistent.units, " ")
        unit = replace(
            unit, "[Unit]\n" => "[Unit]\nWants=$units\nAfter=$units $(external.core) $(external.source)\n";
            count = 1,
        )
        key = PipeWireAORTC.SessionLaunch.GRAPH_MANIFEST_ENV
        unit *= "Environment=" * quote_unit(key * "=" * persistent.digest) * "\n"
    end
    return unit
end

"""
    install(options)

Validate and copy a sealed session package into a fresh `options.destination`.
Supply absolute `package` and `pipewire_prefix` paths. Use `julia_executable`
to select the Julia executable and `julia_sysimage` to pin an absolute image path
for the main RTC process. Supply `git_repository` (the Git directory)
and `git_commit` (the full export commit ID) to select an explicit Git snapshot.
Otherwise use the sibling `<package>.git` repository when Git is available.
Optionally select `persistent_graph_owners = true` with the independent core
and source bindings to generate separately supervised graph units.
Pass `graph_installation` to attach to matching graph units from an existing
installation, or use `external_owner` entries of the form `role=unit.service`
to bind declared bootstrap roles to services supplied by the site.
Return the installation path. Service activation remains a separate operator action.
"""
function install(options)
    source = realpath(options.package)
    prefix = realpath(options.pipewire_prefix)
    repository = get(options, :git_repository, nothing)
    commit = get(options, :git_commit, nothing)
    (repository === nothing) == (commit === nothing) ||
        throw(ArgumentError("supply both git_repository and git_commit for export verification"))
    if repository === nothing
        repository, commit = GitExport.export_pin(source)
    end
    destination = abspath(options.destination)
    !(ispath(destination) || islink(destination)) ||
        throw(ArgumentError("install destination must be new"))
    julia = D.selected_julia_executable(
        get(options, :julia_executable, Base.julia_cmd().exec[1])
    )
    persistent_graph_owners = get(options, :persistent_graph_owners, false)
    graph_installation = get(options, :graph_installation, nothing)
    external_owners = external_owner_bindings(get(options, :external_owner, String[]))
    persistent_graph_owners && graph_installation !== nothing &&
        throw(ArgumentError("choose generated graph owners or an existing graph installation"))
    sysimage = selected_sysimage(get(options, :julia_sysimage, nothing))
    for name in (".git", GitExport.DIRECTORY)
        entry = joinpath(source, name)
        !(ispath(entry) || islink(entry)) ||
            throw(ArgumentError("install requires an exported application without $name"))
    end
    follow_symlinks = repository === nothing
    if follow_symlinks
        source_spec = session_spec(source, prefix)
        haskey(source_spec["artifacts"], "systemd/pipewireao-session@.service") &&
            throw(ArgumentError("export must not seal an installation-specific session unit"))
        session_assets(source_spec, source, prefix)
        # Copying entries into a reserved directory needs the same containment
        # check as copying the whole tree with cp.
        target = joinpath(realpath(dirname(destination)), basename(destination))
        startswith(target, joinpath(source, "")) &&
            throw(ArgumentError("install destination cannot be inside the exported application"))
    end
    files = follow_symlinks ? readdir(source) : PipeWireAORTC.InstrumentExport.application_files(source)
    # Exclusive creation leaves a competing install or a preexisting link alone.
    mkdir(destination)
    created = lstat(destination)
    try
        for file in files
            output = joinpath(destination, file)
            mkpath(dirname(output))
            cp(joinpath(source, file), output; follow_symlinks)
            follow_symlinks || (isfile(output) && !islink(output)) ||
                throw(ArgumentError("installed export asset must be a regular file: $file"))
        end
        follow_symlinks || GitExport.verify_install!(destination, realpath(repository), commit)
        return finish_install(
            destination, prefix, julia, commit;
            persistent_graph_owners, graph_installation, external_owners, sysimage,
        )
    catch
        Base.samefile(created, lstat(destination)) && rm(destination; recursive = true)
        rethrow()
    end
end

function resolved_package(environment)
    entry = Base.explicit_manifest_uuid_path(
        joinpath(environment, "Project.toml"), Base.PkgId(PipeWireAORTC)
    )
    entry isa AbstractString && isfile(entry) ||
        throw(ArgumentError("pinned RTC package is unavailable in the application environment"))
    return dirname(dirname(entry))
end

unit_template_path(environment, name) =
    joinpath(resolved_package(environment), "assets", "deployment", name)

resolved_unit_template(environment) =
    read(unit_template_path(environment, "pipewireao-session@.service.in"), String)

selected_sysimage(::Nothing) = nothing
function selected_sysimage(path::AbstractString)
    isabspath(path) && !any(character -> occursin(character, path), ('\0', '\n', '\r')) &&
        isfile(path) || throw(ArgumentError("--julia-sysimage requires an absolute file path"))
    return realpath(path)
end

# Run this check in the image process, against the installer-selected Project.
# Manifest lookup selects the immutable source tree and resolves extensions
# through their parent package. Only the selected Julia supplies stdlibs.
const SYSIMAGE_PACKAGE_CHECK = raw"""
    function check_sysimage_packages(project, sources)
        rtc = Base.PkgId(Base.UUID("a3e2c7da-f73f-4284-8482-36ac422b34e6"), "PipeWireAORTC")
        haskey(sources, rtc) || error("Julia sysimage does not preload PipeWireAORTC")
        for (id, embedded) in sources
            id.uuid === nothing && error("Julia sysimage preloads unregistered module $(id.name)")
            selected = Base.explicit_manifest_uuid_path(project, id)
            if selected === nothing
                selected = Base.manifest_uuid_path(Sys.STDLIB, id)
            end
            selected isa String && isfile(selected) ||
                error("Julia sysimage package $(id.name) is unavailable in the installed environment")
            embedded isa String && isabspath(embedded) &&
                normpath(embedded) == normpath(selected) ||
                error("Julia sysimage uses a different $(id.name) package source")
        end
        return nothing
    end
    """

function validate_sysimage(julia, project, sysimage)
    code = SYSIMAGE_PACKAGE_CHECK * raw"""
        project, image = ARGS
        realpath(unsafe_string(Base.JLOptions().image_file)) == image ||
            error("Julia loaded a different sysimage")
        sources = Dict(id => pathof(mod) for (id, mod) in Base.loaded_modules
                       if Base.in_sysimage(id) && mod !== Core && mod !== Base && mod !== Main)
        check_sysimage_packages(project, sources)
        """
    receipt = C.run_checked(
        [julia, "--startup-file=no", "--compiled-modules=existing", "--threads=1,0",
         "--project=" * project, "--sysimage=" * sysimage, "-e", code, "--",
         joinpath(project, "Project.toml"), sysimage];
        timeout = 60, maximum_output_bytes = 64 * 1024,
    )
    receipt.returncode == 0 || throw(ArgumentError("cannot validate Julia sysimage: " * strip(receipt.stderr)))
    return nothing
end

# Keep the chosen RTC build across upgrades and rollbacks that reuse a depot.
# Julia validates its normal dependency caches and selects its own cache filenames.
const LOAD_INSTALLED_RTC = raw"""
    using PipeWireAORTC
    id = Base.PkgId(PipeWireAORTC)
    id.uuid == Base.UUID("a3e2c7da-f73f-4284-8482-36ac422b34e6") ||
        error("unexpected installed RTC package")
    source = Base.explicit_manifest_uuid_path(Base.active_project(), id)
    source isa String && realpath(pathof(PipeWireAORTC)) == realpath(source) ||
        error("unexpected installed RTC source")
    """

const STAGE_PACKAGE_CACHE = LOAD_INSTALLED_RTC * raw"""
    for (id, origin) in Base.pkgorigins
        cache = origin.cachepath
        isnothing(cache) && continue
        target = mkpath(Base.compilecache_dir(id))
        dirname(cache) == target && continue
        native = Base.ocachefile_from_cachefile(cache)
        for path in (cache, native)
            # Some dependencies have a serialized cache only.
            path == native && !isfile(native) && continue
            destination = joinpath(target, basename(path))
            Base.samefile(path, destination) && continue
            try
                hardlink(path, destination)
            catch err
                # Separate file systems or read-only system-owned caches.
                err isa Base.IOError && err.code in (Base.UV_EXDEV, Base.UV_EPERM,
                    Base.UV_EACCES, Base.UV_ENOTSUP, Base.UV_EMLINK) || rethrow()
                cp(path, destination)
            end
        end
    end
    """

function cache_environment(declared, package, prefix, external)
    settings = Dict{String,String}()
    for name in ("JULIA_DEPOT_PATH", "JULIA_LOAD_PATH", "JULIA_CPU_TARGET")
        haskey(declared, name) || continue
        value = replace(declared[name], "@PACKAGE@" => package, "@PREFIX@" => prefix)
        if external !== nothing
            value = replace(value, "@RUNTIME@/@REMOTE@" => external.socket, "@REMOTE@" => external.socket)
        end
        # Invocation-specific paths can only be resolved at service start.
        occursin(r"@[A-Z_]+@", value) && continue
        get(ENV, name, nothing) == value || (settings[name] = value)
    end
    return settings
end

function prepare_package_cache(julia, project; settings = Dict{String,String}(), direct = false)
    mkdir(joinpath(project, ScienceExport.RTC_CACHE_DIRECTORY))
    stage = Cmd([julia, ScienceExport.RTC_JULIA_FLAGS..., "--project=" * project,
                 "-e", ScienceExport.RTC_CACHE_SETUP * STAGE_PACKAGE_CACHE])
    verify = raw"""
        id = Base.identify_package("PipeWireAORTC")
        caches = filter(path -> endswith(path, ".ji"), readdir(Base.compilecache_dir(id); join = true))
        Base.compilecache_freshest_path(id; cachepaths = caches) === nothing &&
            error("installed RTC package image is unusable")
        """ * LOAD_INSTALLED_RTC
    check = Cmd(ScienceExport.rtc_command(julia, project; installed_cache = true, entrypoint = verify))
    # A managed RTC can re-exec after applying its session-only environment.
    environments = !direct && !isempty(settings) ? (Dict{String,String}(), settings) : (settings,)
    for env in environments
        run(addenv(stage, env...))
    end
    for env in environments
        run(addenv(check, env...))
    end
    return nothing
end

function finish_install(
    destination, prefix, julia, commit;
    persistent_graph_owners = false, graph_installation = nothing,
    external_owners = Dict{String,String}(), sysimage = nothing,
)
    installed_spec = session_spec(destination, prefix)
    haskey(installed_spec["artifacts"], "systemd/pipewireao-session@.service") &&
        throw(ArgumentError("export must not seal an installation-specific session unit"))
    executable = D.session_executable(installed_spec, destination, prefix)
    session_assets(installed_spec, destination, prefix)
    isfile(executable) && (stat(executable).mode & 0o111) != 0 ||
        throw(ArgumentError("installed RTC Julia launcher is unavailable"))
    bin = joinpath(destination, "bin")
    mkpath(bin)
    launcher = joinpath(bin, "pipewireao-rtc-session")
    environment = D.application_environment(installed_spec, destination)
    template = resolved_unit_template(environment)
    validated_image = if sysimage !== nothing
        (occursin(INSTALLED_COMMAND, template) || occursin("@RTC_COMMAND@", template)) &&
            occursin("@ACTIVATION_ENVIRONMENT@", template) ||
            throw(ArgumentError("pinned RTC package does not support a Julia sysimage"))
        identity = PipeWireAORTC.SessionLaunch.graph_file_identity(sysimage)
        validate_sysimage(julia, environment, sysimage)
        identity
    end
    launch = PipeWireAORTC.SessionLaunch
    external = launch.external_services()
    explicit_attach = graph_installation !== nothing || !isempty(external_owners)
    direct_template = unit_template_path(environment, "pipewireao-session-direct@.service.in")
    explicit_attach && (external === nothing || !isfile(direct_template)) && throw(
        ArgumentError("external graph services require independent core and source bindings and direct RTC support"),
    )
    validate_external_owner_roles(installed_spec, external_owners)
    if persistent_graph_owners
        external === nothing &&
            throw(ArgumentError("persistent graph owners require independent core and source bindings"))
        isfile(joinpath(resolved_package(environment), "src", "deployment", "persistent_graphs.jl")) ||
            throw(ArgumentError("pinned RTC package does not support persistent graph owners"))
    end
    historical_publish = occursin(r"(?m)^ExecStartPost=.*\bpublish\b", template)
    script = installed_launcher(julia; environment, commit, historical_publish,
        installed_cache = occursin(INSTALLED_COMMAND, template))
    if haskey(installed_spec["artifacts"], "bin/pipewireao-rtc-session")
        sealed = read(launcher, String)
        # Preserve the exact historical script and its original bindings.
        (sealed == script ||
         sealed == installed_launcher(julia; environment, commit, historical_publish = false) ||
         sealed == installed_launcher(julia; environment, commit, historical_publish = true) ||
         sealed == installed_launcher(
             julia; environment, commit, minimal_prepare = false, historical_publish = true
         ) ||
         sealed == installed_launcher(julia; environment, commit, legacy = true)) || throw(
            ArgumentError(
                "sealed session launcher differs from the selected Julia executable"
            ),
        )
    else
        write(launcher, script)
    end
    chmod(launcher, 0o755)
    systemd = joinpath(destination, "systemd")
    mkpath(systemd)
    referenced = graph_installation === nothing ? nothing :
        launch.reference_persistent_graphs(graph_installation, destination, prefix, installed_spec, external)
    # An existing graph service has already qualified its declared inputs.
    prepare_owners = filter(installed_spec["owners"]) do owner
        role = owner["role"]
        !haskey(external_owners, role) && (referenced === nothing || !haskey(referenced.owners, role))
    end
    # Graph preparation validates controller recovery before the optical image build.
    PipeWireAORTC.GraphStartup.precompile!(julia, destination, environment, prepare_owners)
    if external === nothing
        owners = filter(!D.uses_external_stream, installed_spec["owners"])
        PipeWireAORTC.HILStartup.install!(environment, destination, owners, prefix)
    end
    persistent = persistent_graph_owners ? launch.install_persistent_graphs!(
        destination, prefix, installed_spec, external
    ) : nothing
    graphs = referenced === nothing ? persistent : referenced
    direct = if external !== nothing && isfile(direct_template)
        install_direct!(
            destination, prefix, julia, environment, installed_spec, external, external_owners, graphs;
            generated_graphs = persistent !== nothing, explicit = explicit_attach,
        )
    end
    explicit_attach && direct === nothing &&
        throw(ArgumentError("direct RTC installation requires independently supplied controller graph services"))
    direct === nothing || (template = read(direct_template, String))
    installed_cache = occursin(INSTALLED_COMMAND, template)
    if installed_cache
        settings = cache_environment(installed_spec["session-runtime"]["environment"],
                                     destination, prefix, external)
        prepare_package_cache(julia, environment;
                              settings, direct = direct !== nothing)
    end
    activation = occursin("@ACTIVATION_ENVIRONMENT@", template) ?
        install_activation!(
            destination, prefix, julia, environment, launcher, installed_spec, commit;
            sysimage, validated_image, direct, installed_cache,
        ) : nothing
    unit = installed_unit(
        template, installed_spec;
        launcher, package = destination, prefix, executable, external, persistent, activation, direct,
    )
    write(joinpath(systemd, "pipewireao-session@.service"), unit)
    return destination
end

"""
    main(argv=ARGS)

Parse installer arguments and return the installed package path. Required flags
are `--package`, `--destination` and `--pipewire-prefix`. Use the optional
`--julia-sysimage` option to pin a main-process image and
`--persistent-graph-owners` to select separately supervised graph units.
Use `--graph-installation` to select an existing graph installation or repeat
`--external-owner role=unit.service` for site-owned services.
"""
function main(argv = ARGS)
    args = C.cli_arguments(
        argv;
        required = ["package", "destination", "pipewire-prefix"],
        allowed = ["julia-executable", "julia-sysimage", "git-repository", "git-commit", "graph-installation"],
        flags = ["persistent-graph-owners"],
        repeats = ["external-owner"],
    )
    return install(args)
end

