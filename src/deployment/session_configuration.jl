_pupil_output_enabled(enabled) = throw(ArgumentError("pupil_output must be Boolean"))
_pupil_output_enabled(::Bool) = nothing
_widen_session_ports!(graph, ::AbstractDict{String,Any}) = false
function _widen_session_ports!(graph, port)
    graph["ports"] = Dict{String,Any}[Dict{String,Any}(item) for item in graph["ports"]]
    return true
end
_gui_defaults!(defaults, path, document, spec) = nothing
function _gui_defaults!(defaults, path, document::AbstractDict, spec)
    get(document, "schema_version", nothing) == 11 && haskey(document, "view") ||
        return nothing
    _gui_session_defaults!(defaults, path, get(document, "session", nothing), spec)
    return nothing
end
_gui_session_defaults!(defaults, path, session, spec) = nothing
function _gui_session_defaults!(defaults, path, session::AbstractDict, spec)
    label = get(session, "label", get(spec, "name", nothing))
    _gui_session_label(label)
    if !haskey(session, "label")
        session["label"] = label
        push!(defaults, path)
    end
    return nothing
end
_gui_session_label(label) =
    throw(ArgumentError("GUI session label must be a nonempty string"))
_gui_session_label(label::AbstractString) =
    !isempty(label) || throw(ArgumentError("GUI session label must be a nonempty string"))

function prepare_pupil_output!(application, spec, files, prefix)
    path = joinpath(application, "simulation.conf")
    isfile(path) || return false
    simulation = D.decode(path, prefix)
    enabled =
        get(simulation, "version", nothing) == 5 || get(simulation, "pupil_output", false)
    _pupil_output_enabled(enabled)
    enabled || return false
    get(simulation, "version", nothing) in (3, 5) ||
        throw(ArgumentError("pupil_output requires version 3 or 5"))
    role = spec["source-owner"]
    Base.require(Main, :AdaptiveOpticsSim)
    Base.require(Main, :AdaptiveOpticsSimPipeWireHIL)
    plant = simulation["plant"]
    contract = Base.invokelatest(
        pupil_output_port_contract,
        D.relative_asset(application, plant["definition"]);
        settings = get(plant, "settings", Dict()),
        simulation_graph = get(plant, "graph", "production"),
    )
    session = first(files).document
    sources = get!(session, "sources", Any[])
    name = "simulator-pupil-output"
    any(entry -> entry["node.name"] == name, sources) &&
        throw(ArgumentError("scientific pupil source is generated by the simulator owner"))
    push!(
        sources,
        Dict(
            "node.name" => name,
            "ownership" => "external",
            "ports" =>
                [merge(Dict("name" => "output_1", "direction" => "output"), contract)],
        ),
    )
    owners = spec["node-owners"]
    haskey(owners, name) &&
        throw(ArgumentError("duplicate scientific pupil node ownership"))
    owners[name] = role
    if get(simulation, "version", nothing) == 5 &&
        get(simulation, "applied_command_observation", false)
        options = AOSOwner.configuration(path)
        applied = "simulator-" * options.mirror * "-applied"
        any(entry -> entry["node.name"] == applied, sources) &&
            throw(ArgumentError("duplicate adopted physical-command source"))
        haskey(owners, applied) &&
            throw(ArgumentError("duplicate adopted physical-command ownership"))
        push!(
            sources,
            Dict(
                "node.name" => applied,
                "ownership" => "external",
                "ports" => [
                    Dict(
                        "name" => "output_1",
                        "direction" => "output",
                        "shape" => [options.command_count],
                        "element-type" => "F32_LE",
                        "layout" => "ROW_MAJOR",
                        "schema" => Schemas.identifier("applied_dm_command_opd_um"),
                        "rate" => string(options.rate) * "/1",
                    ),
                ],
            ),
        )
        owners[applied] = role
    end
    return true
end

# PipeWireAO exposes the wire enum, but no public Julia-type conversion. Keep this
# serialization boundary explicit, including Bool's distinct representation.
wire_element_type(::Type{Bool}) = string(PipeWireAO.NdArray.BOOL8)
wire_element_type(::Type{Int8}) = string(PipeWireAO.NdArray.I8)
wire_element_type(::Type{UInt8}) = string(PipeWireAO.NdArray.U8)
wire_element_type(::Type{Int16}) = string(PipeWireAO.NdArray.I16_LE)
wire_element_type(::Type{UInt16}) = string(PipeWireAO.NdArray.U16_LE)
wire_element_type(::Type{Int32}) = string(PipeWireAO.NdArray.I32_LE)
wire_element_type(::Type{UInt32}) = string(PipeWireAO.NdArray.U32_LE)
wire_element_type(::Type{Int64}) = string(PipeWireAO.NdArray.I64_LE)
wire_element_type(::Type{UInt64}) = string(PipeWireAO.NdArray.U64_LE)
wire_element_type(::Type{Float32}) = string(PipeWireAO.NdArray.F32_LE)
wire_element_type(::Type{Float64}) = string(PipeWireAO.NdArray.F64_LE)
wire_element_type(::Type{T}) where {T} =
    throw(ArgumentError("unsupported session ndarray element type $T"))

function port_contract(format)
    return Dict(
        "shape" => collect(Int, format.shape),
        "element-type" => wire_element_type(format.element_type),
        "schema" => format.schema,
    )
end

function reference_roots!(roots, value::AbstractDict)
    if haskey(value, "\$ref")
        pointer = graph_reference_pointer(value)
        parts = split(pointer, '/'; keepempty = true)
        push!(roots, length(parts) > 1 ? parts[2] : "")
    else
        for item in values(value)
            reference_roots!(roots, item)
        end
    end
    return roots
end
function reference_roots!(roots, value::AbstractVector)
    for item in value
        reference_roots!(roots, item)
    end
    return roots
end
reference_roots!(roots, value) = roots

function graph_contract_context(application, declarations, prefix)
    Base.require(Main, :FilterGraphPipeWire)
    result = Dict{String,Any}()
    for entry in declarations
        path = D.relative_asset(application, entry["path"])
        declaration = D.decode(path, prefix)
        name = declaration["node.name"]
        haskey(result, name) &&
            throw(ArgumentError("duplicate graph contract node name: $name"))
        contracts = Base.invokelatest(graph_port_contracts, path; metadata = true)
        for ports in values(contracts), contract in values(ports)
            contract["element-count"] = foldl(Base.checked_mul, contract["shape"]; init = 1)
        end
        result[name] = contracts
    end
    return result
end

# Session declarations may expose a subset of a prepared graph's ports, but
# missing metadata comes from those exact ports. Explicit physical quantities must
# agree even when shapes and element types match.
function validate_session_graph_contracts(session, contracts)
    for graph in get(session, "graphs", [])
        name = graph["node.name"]
        haskey(contracts, name) || continue # Other external owners are not FilterGraphs declarations.
        actual = contracts[name]
        # Reference resolution can infer string-only dictionaries when all
        # numeric metadata was omitted. Widen before adding prepared shapes.
        any(port -> _widen_session_ports!(graph, port), graph["ports"])
        for port in graph["ports"]
            section = if get(port, "parameter", false)
                "parameters"
            elseif port["direction"] == "input"
                "inputs"
            else
                "outputs"
            end
            portname = port["name"]
            haskey(actual[section], portname) || throw(
                ArgumentError(
                    "session graph $name has no prepared $section port $portname"
                ),
            )
            expected = actual[section][portname]
            for field in ("shape", "element-type", "schema")
                get!(port, field, deepcopy(expected[field])) == expected[field] || throw(
                    ArgumentError(
                        "session graph $name port $portname $field differs from its prepared graph: expected $(repr(expected[field])), got $(repr(get(port,field,nothing)))",
                    ),
                )
            end
        end
    end
    return nothing
end

"Resolve references across the composed session and core before validation and sealing."
function prepare_session_configuration!(
    application,
    spec,
    declarations,
    instrumentpath,
    prefix;
    dimensions::AbstractDict = Dict(),
    mirror_controls::AbstractDict = Dict(),
    calibration::AbstractDict = Dict(),
    configurations = [],
    queue_inputs = D.PortAddress[],
)
    files = [map(("session", "core")) do field
        path = D.relative_asset(application, spec[field])
        (; path, format = "spa-json", document = D.decode(path, prefix))
    end...]
    InstrumentDefinition.array_value(configurations) ||
        throw(ArgumentError("configuration-files must be an array"))
    paths = Set(entry.path for entry in files)
    gui_defaults = Set{String}()
    for declaration in configurations
        InstrumentDefinition.object_value(declaration) &&
        Set(keys(declaration)) == Set(["path", "format"]) ||
            throw(ArgumentError("configuration-files entries require path and format"))
        path = D.relative_asset(application, declaration["path"])
        path in paths && throw(ArgumentError("duplicate configuration file: $path"))
        push!(paths, path)
        format = declaration["format"]
        document = read_configuration(path, format, prefix)
        _gui_defaults!(gui_defaults, path, document, spec)
        push!(files, (; path, format, document))
    end
    pupil_output = prepare_pupil_output!(application, spec, files, prefix)
    roots = Set{String}()
    for entry in files
        reference_roots!(roots, entry.document)
    end
    simulation_path = joinpath(application, "simulation.conf")
    metadata_simulation =
        isfile(simulation_path) ? D.decode(simulation_path, prefix) : Dict()
    owners = get(spec, "node-owners", nothing)
    session_header = "Generated by PipeWireAORTC from application configuration; edit the YAML source and rebuild."
    if isempty(roots) && !pupil_output && isempty(declarations)
        session = first(files).document
        links = D.session_links(session)
        added_sinks = queue_sinks!(session, queue_inputs, links, owners)
        queue_metadata_profiles!(
            files[2].document, links, Dict(), metadata_simulation
        )
        foreach(entry -> Schemas.validate(entry.document), files)
        added_sinks &&
            ScienceExport.write_spa_config(first(files).path, session; header = session_header)
        ScienceExport.write_spa_config(files[2].path, files[2].document)
        if !isempty(gui_defaults)
            for entry in files[3:end]
                entry.path in gui_defaults || continue
                write_configuration(
                    entry.path,
                    entry.format,
                    entry.document;
                    header = session_header,
                )
            end
        end
        return nothing
    end
    instrument = Common.read_json(D.relative_asset(application, instrumentpath))
    context = graph_context(instrument; dimensions, mirror_controls, calibration)
    if "graphs" in roots || !isempty(declarations)
        context["graphs"] = graph_contract_context(application, declarations, prefix)
    end
    if "simulation" in roots
        # The same cold physical/model context used for graph authoring is also
        # available to generic application documents, including time axes.
        simulation = D.decode(D.relative_asset(application, "simulation.conf"), prefix)
        plant = simulation["plant"]
        declaration = InstrumentConfiguration.load_simulation(
            D.relative_asset(application, plant["definition"])
        )
        configured = InstrumentConfiguration.settings(
            declaration, get(plant, "settings", Dict())
        )
        context["simulation"] = InstrumentConfiguration.configuration_context(
            declaration, configured
        )["simulation"]
    end
    if "simulator" in roots
        Base.require(Main, :AdaptiveOpticsSim)
        Base.require(Main, :AdaptiveOpticsSimPipeWireHIL)
        simulation = D.decode(D.relative_asset(application, "simulation.conf"), prefix)
        plant = simulation["plant"]
        definition = D.relative_asset(application, plant["definition"])
        if get(simulation, "version", nothing) in (4, 6)
            options = AOSOwner.configuration(joinpath(application, "simulation.conf"))
            AOSOwner.requires_proper(options) && Base.require(Main, :Proper)
            context["simulator"] = Base.invokelatest(
                external_pupil_port_contracts,
                definition;
                settings = get(plant, "settings", Dict()),
                chopping = options.plant.chopping,
            )
        elseif get(simulation, "version", nothing) == 5
            context["simulator"] = Dict(
                "pupil" => Base.invokelatest(
                    pupil_output_port_contract,
                    definition;
                    settings = get(plant, "settings", Dict()),
                    simulation_graph = plant["graph"],
                ),
            )
        else
            context["simulator"] = Base.invokelatest(
                simulator_port_contracts,
                definition;
                settings = get(plant, "settings", Dict()),
                simulation_graph = get(plant, "graph", "production"),
            )
            if get(simulation, "version", nothing) == 3 && pupil_output
                context["simulator"]["pupil"] = Base.invokelatest(
                    pupil_output_port_contract,
                    definition;
                    settings = get(plant, "settings", Dict()),
                    simulation_graph = get(plant, "graph", "production"),
                )
            end
        end
    end
    # Resolve every document first so a bad reference cannot partly rewrite it.
    prepared = map(files) do entry
        document = graph_configuration_value(entry.document, context)
        entry.path == first(files).path &&
            haskey(context, "graphs") &&
            validate_session_graph_contracts(document, context["graphs"])
        (; entry.path, entry.format, document)
    end
    session = first(prepared).document
    links = D.session_links(session)
    queue_sinks!(session, queue_inputs, links, owners)
    queue_metadata_profiles!(
        prepared[2].document,
        links,
        get(context, "graphs", Dict()),
        metadata_simulation,
    )
    foreach(entry -> Schemas.validate(entry.document), prepared)
    header = "Generated by PipeWireAORTC from the instrument, prepared graph contracts and selected simulator settings; do not edit.\nEdit the instrument source and rebuild."
    for entry in prepared
        write_configuration(entry.path, entry.format, entry.document; header)
    end
    return nothing
end

function read_configuration(path, format, prefix)
    format == "spa-json" && return D.decode(path, prefix)
    format == "yaml" && return Common.read_yaml(path)
    throw(ArgumentError("unsupported configuration file format: $format"))
end

function write_configuration(path, format, document; header)
    format == "spa-json" && return ScienceExport.write_spa_config(path, document; header)
    format == "yaml" ||
        throw(ArgumentError("unsupported configuration file format: $format"))
    return Common.write_yaml(path, document; header)
end
