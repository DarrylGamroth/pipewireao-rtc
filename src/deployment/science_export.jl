write_json(path::AbstractString, value) = Common.write_json(path, value)

# Keep the bare-string subset conservative. Native SPA parsers also recognize
# non-JSON numbers such as NaN and Inf, so those strings must remain quoted.
spa_simple_string(value::AbstractString) =
    occursin(r"\A[A-Za-z_][A-Za-z0-9_.-]*\z", value) &&
    !(value in ("true", "false", "null")) &&
    !(lowercase(value) in ("nan", "inf", "infinity"))

function write_spa_value(io::IO, value::AbstractString, depth)
    isvalid(value) || throw(ArgumentError("SPA configuration string must be valid UTF-8"))
    occursin('\0', value) &&
        throw(ArgumentError("SPA configuration strings must not contain NUL"))
    spa_simple_string(value) ? print(io, value) : JSON.json(io, value)
end

write_spa_value(io::IO, value::Union{Nothing,Bool,Integer,AbstractFloat}, depth) =
    JSON.json(io, value)

function write_spa_value(io::IO, value::AbstractDict, depth)
    println(io, '{')
    for (key, item) in pairs(value)
        print(io, "  " ^ (depth + 1))
        write_spa_value(io, key, depth + 1)
        print(io, " = ")
        write_spa_value(io, item, depth + 1)
        println(io)
    end
    print(io, "  " ^ depth, '}')
end

function write_spa_value(io::IO, value::AbstractVector, depth)
    # Full-image selection masks must fit the ordinary 16 MiB graph limit.
    # Whitespace per pixel otherwise dominates a megapixel Boolean mask.
    if eltype(value) === Bool && length(value) >= 64
        print(io, "[ ")
        for item in value
            print(io, item ? "true " : "false ")
        end
        print(io, ']')
        return nothing
    end
    println(io, '[')
    for item in value
        print(io, "  " ^ (depth + 1))
        write_spa_value(io, item, depth + 1)
        println(io)
    end
    print(io, "  " ^ depth, ']')
end

write_spa_value(io::IO, value, depth) =
    throw(ArgumentError("unsupported SPA configuration value: $(typeof(value))"))

function write_spa_header(io::IO, header::AbstractString)
    isvalid(header) && !occursin('\0', header) ||
        throw(ArgumentError("SPA configuration header must be valid text without NUL"))
    for line in split(header, '\n')
        println(io, "# ", line)
    end
    return nothing
end
write_spa_header(io::IO, header) =
    throw(ArgumentError("SPA configuration header must be text"))

"""Write standard relaxed SPA-JSON with a generated-file comment header."""
function write_spa_config(
    path::AbstractString,
    value;
    header = "Generated by PipeWireAORTC; do not edit. Edit the source configuration and rebuild.",
)
    Common.finite_json(value)
    json = JSON.json(value)
    isequal(Common.parse_json(json), value) ||
        throw(ArgumentError("SPA configuration changed during JSON serialization"))
    io = IOBuffer()
    write_spa_header(io, Common.generated_header(header))
    write_spa_value(io, value, 0)
    println(io)
    payload = String(take!(io))
    # Use the upstream parser to verify the exact document that native consumers
    # will read, including its string escaping and native object-key limits.
    parser = joinpath(
        PipeWireAO.LibPipeWire.PipeWireAO_jll.artifact_dir, "bin", "pwao-spa-json-dump"
    )
    mktempdir() do directory
        source = joinpath(directory, "configuration.conf")
        write(source, payload)
        normalized = Common.run_checked([parser, "-N", "-R", source]; timeout = 10)
        normalized.returncode == 0 || throw(
            ArgumentError("PipeWire rejected generated SPA-JSON: $(normalized.stderr)")
        )
        isequal(Common.parse_json(normalized.stdout), value) ||
            throw(ArgumentError("SPA configuration changed during native serialization"))
    end
    mkpath(dirname(path))
    write(path, payload)
    return path
end

_payload_dimension(dimension) =
    throw(ArgumentError("payload dimensions must be positive integers"))
_payload_dimension(::Bool) =
    throw(ArgumentError("payload dimensions must be positive integers"))
_payload_dimension(dimension::Integer) =
    dimension > 0 || throw(ArgumentError("payload dimensions must be positive integers"))
_port_rate(rate) = rate
_port_rate(rate::Integer) = "$rate/1"

function payload_bytes(shape, width::Integer)
    width > 0 || throw(ArgumentError("element width must be positive"))
    count = BigInt(width)
    isempty(shape) && throw(ArgumentError("payload shape must not be empty"))
    for dimension in shape
        _payload_dimension(dimension)
        count *= dimension
        count <= typemax(Int) ||
            throw(ArgumentError("payload shape exceeds addressable size"))
    end
    return Int(count)
end

function validate_parameter(directory::AbstractString, p::Parameter)
    width = get(TYPE_BYTES, p.element_type, nothing)
    width === nothing &&
        throw(ArgumentError("unsupported parameter type: $(p.element_type)"))
    all(x -> x > 0, p.shape) ||
        throw(ArgumentError("parameter shape must be positive: $(p.name)"))
    path = joinpath(directory, p.file)
    expected = payload_bytes(p.shape, width)
    isfile(path) && !islink(path) && filesize(path) == expected || throw(
        ArgumentError(
            "$(p.name) requires $expected bytes for $(p.element_type)$(p.shape): $path"
        ),
    )
    bytes = read(path)
    if p.element_type == "Bool"
        all(x -> x <= 0x01, bytes) ||
            throw(ArgumentError("$(p.name) Bool payload requires zero/one bytes"))
    elseif p.element_type == "F32_LE"
        all(isfinite, reinterpret(Float32, bytes)) ||
            throw(ArgumentError("nonfinite parameter payload: $path"))
    elseif p.element_type == "F64_LE"
        all(isfinite, reinterpret(Float64, bytes)) ||
            throw(ArgumentError("nonfinite parameter payload: $path"))
    end
    return path
end

function port(
    name,
    direction,
    shape,
    schema,
    element_type = nothing;
    parameter = false,
    rate = nothing,
)
    contract = get(Schemas.BY_ID, schema, nothing)
    element_type === nothing &&
        (element_type = contract === nothing ? "F32_LE" : contract["wire_type"])
    Schemas.validate(Dict("schema" => schema, "element-type" => element_type))
    value = Dict{String,Any}(
        "name" => name,
        "direction" => direction,
        "element-type" => element_type,
        "shape" => collect(shape),
        "schema" => schema,
    )
    parameter && (value["parameter"] = true)
    rate === nothing || (value["rate"] = _port_rate(rate))
    return value
end

const RTC_JULIA_FLAGS = ("--startup-file=no", "--threads=1,0")
const RTC_ENTRYPOINT = "using PipeWireAORTC; exit(PipeWireAORTC.MediaSession.main(ARGS))"

"Exact Julia arguments shared by launcher generation and process verification."
rtc_arguments(julia::AbstractString, project::AbstractString, config::AbstractString) =
    String[
        julia,
        RTC_JULIA_FLAGS...,
        "--project="*project,
        "-e",
        RTC_ENTRYPOINT,
        "--",
        "-c",
        config,
    ]

function rtc_launcher()
    return raw"""#!/bin/sh
# Generated by PipeWireAORTC.ScienceExport.stage_rtc! from the Julia session policy.
# Source: src/deployment/science_export.jl; regenerate with ScienceExport.stage_rtc!.
exec "${PIPEWIREAORTC_JULIA:?PIPEWIREAORTC_JULIA is required}" """ *
           join(RTC_JULIA_FLAGS, " ") *
           raw""" --project="${PIPEWIREAORTC_PROJECT:?PIPEWIREAORTC_PROJECT is required}" -e '""" *
           RTC_ENTRYPOINT *
           raw"""' -- "$@"
"""
end

"""Generate the headless RTC Julia launcher in a package-owned `rtc/bin` directory.

The launcher loads the application environment's RTC dependency. Only `rtc/bin`
is reserved for generated runtime files; authored RTC configuration is preserved.
"""
function stage_rtc!(package)
    target = joinpath(package, "rtc")
    islink(target) && throw(ArgumentError("staged RTC directory must not be a symlink"))
    bin = joinpath(target, "bin")
    islink(bin) && throw(ArgumentError("staged RTC bin directory must not be a symlink"))
    if ispath(bin)
        isdir(bin) && all(name -> name == "pipewireao-rtc", readdir(bin)) ||
            throw(ArgumentError("staged RTC bin directory contains unowned files"))
        islink(joinpath(bin, "pipewireao-rtc")) &&
            throw(ArgumentError("staged RTC launcher must not be a symlink"))
    end
    temporary = mktempdir(package; prefix = "rtc-stage-")
    try
        launcher = joinpath(temporary, "bin/pipewireao-rtc")
        mkpath(dirname(launcher))
        write(launcher, rtc_launcher())
        chmod(launcher, 0o755)
        validate_rtc(temporary)
        mkpath(bin)
        mv(launcher, joinpath(bin, "pipewireao-rtc"); force = true)
    finally
        ispath(temporary) && rm(temporary; recursive = true)
    end
    validate_rtc(target)
    return target
end

function validate_rtc(target)
    islink(target) && throw(ArgumentError("sealed RTC directory must not be a symlink"))
    bin = joinpath(target, "bin")
    isdir(bin) && !islink(bin) ||
        throw(ArgumentError("sealed RTC bin directory is missing or linked"))
    launcher = joinpath(target, "bin/pipewireao-rtc")
    isfile(launcher) && !islink(launcher) ||
        throw(ArgumentError("sealed RTC Julia launcher is missing"))
    (stat(launcher).mode & 0o111) != 0 ||
        throw(ArgumentError("sealed RTC Julia launcher is not executable"))
    read(launcher, String) == rtc_launcher() || throw(
        ArgumentError(
            "sealed RTC Julia launcher differs from the selected policy entrypoint"
        ),
    )
    readdir(bin) == ["pipewireao-rtc"] || throw(
        ArgumentError(
            "sealed RTC bin directory contains assets outside the Julia launcher"
        ),
    )
    return nothing
end

