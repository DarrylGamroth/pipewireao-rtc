module GraphStartup

using ..DeploymentConfiguration: bootstrap_instance_key, uses_external_stream

const ENTRY = "using PipeWireAORTC; PipeWireAORTC.GraphOwner.main(ARGS)"
const DIRECTORY = "graph-startup"
const GENERATED_HEADER = "# Generated by PipeWireAORTC from the exported graph owner."

function owner_arguments(owner)
    uses_external_stream(owner) && return nothing
    argv = owner["argv"]
    idx = findfirst(==(ENTRY), argv)
    idx === nothing && return nothing
    idx + 1 < length(argv) && argv[idx + 1] == "--" || return nothing
    return argv[idx + 2:end]
end

function stage!(package, owners; replace_generated = false)
    for owner in owners
        args = owner_arguments(owner)
        args === nothing && continue
        role = owner["role"]
        directory = joinpath(package, DIRECTORY, role, "ExportedGraphWarmup", "src")
        mkpath(directory)
        path = joinpath(directory, "ExportedGraphWarmup.jl")
        if ispath(path) || islink(path)
            replace_generated && isfile(path) && !islink(path) &&
                open(readline, path) == GENERATED_HEADER ||
                throw(ArgumentError("graph warmup workload must be generated by export"))
        end
        # Include graph inputs in the cache identity through the deployment
        # seal, without embedding an export or installation absolute path.
        open(path, "w") do io
            println(io, """
                $GENERATED_HEADER
                module ExportedGraphWarmup
                const root = normpath(joinpath(@__DIR__, "..", "..", "..", ".."))
                for file in ("deployment.conf", "Project.toml", "Manifest.toml")
                    Base.include_dependency(joinpath(root, file); track_content = true)
                end
                function qualify(arguments = $(repr(args)))
                    rtc = Base.require(Main, :PipeWireAORTC)
                    Base.require(Main, :FilterGraphPipeWire)
                    return Base.invokelatest(qualify, rtc, arguments)
                end
                function qualify(rtc, arguments)
                    bindings = Dict(
                        "PACKAGE" => root,
                        "RUNTIME" => tempdir(),
                        "REMOTE" => "offline-graph-warmup",
                        $(repr(bootstrap_instance_key(role))) => "1",
                    )
                    args = map(arg -> rtc.DeploymentConfiguration.substitute(arg, bindings), arguments)
                    return rtc.GraphOwner.precompile_graph_warmup(args)
                end
                if ccall(:jl_generating_output, Cint, ()) == 1
                    const PrecompileTools = Base.require(Base.PkgId(Base.UUID("aea7be01-6a6a-4083-8856-8a6e6704d82a"), "PrecompileTools"))
                    @eval PrecompileTools.@compile_workload qualify()
                end
                end
                """)
        end
    end
    return nothing
end

# The package-directory workload has a shared top-level name. Keep its
# native cache local to the installation while reusing the application's
# ordinary dependency depots.
cache_depot(workload) = joinpath(workload, "depot")

function workload_directory(package, owner)
    owner_arguments(owner) === nothing && return nothing
    path = joinpath(package, DIRECTORY, owner["role"])
    isfile(joinpath(path, "ExportedGraphWarmup", "src", "ExportedGraphWarmup.jl")) ||
        return nothing
    return path
end

function precompile!(julia, package, environment, owners)
    for owner in owners
        root = workload_directory(package, owner)
        args = owner_arguments(owner)
        at_install = args !== nothing &&
            any(arg -> first(split(arg, '='; limit = 2)) == "--qualify-at-install", args)
        if root === nothing
            at_install && throw(ArgumentError("missing qualification workload for $(owner["role"])"))
            continue
        end
        argv = owner["argv"]
        flags = argv[2:(findfirst(==("-e"), argv) - 1)]
        flags = filter(flag -> startswith(flag, "-O") || startswith(flag, "--threads="), flags)
        code = "pushfirst!(LOAD_PATH, popfirst!(ARGS)); using ExportedGraphWarmup"
        # A cached image may bypass compilation. Qualify the installed owner's
        # final arguments explicitly, independently of the compile workload.
        code *= "; ExportedGraphWarmup.qualify(ARGS)"
        command_args = [julia, flags..., "--startup-file=no", "--project=" * environment,
                        "-e", code, "--", root]
        append!(command_args, args)
        command = Cmd(command_args)
        depots = join([cache_depot(root); DEPOT_PATH], ':')
        run(addenv(command, "JULIA_DEPOT_PATH" => depots, "JULIA_LOAD_PATH" => "@:@stdlib"))
    end
    return nothing
end

function configure_owner!(argv, package, owner)
    path = workload_directory(package, owner)
    path === nothing && return nothing
    index = findfirst(==(ENTRY), argv)
    argv[index] = """
        pushfirst!(LOAD_PATH, $(repr(path)))
        pushfirst!(DEPOT_PATH, $(repr(cache_depot(path))))
        try
            Base.require(Main, :ExportedGraphWarmup)
        finally
            popfirst!(DEPOT_PATH)
            popfirst!(LOAD_PATH)
        end
        $ENTRY
        """
    # Install owns cache generation. An invalid or missing cache falls back
    # to loading graph code without running the offline workload on launch.
    insert!(argv, findfirst(==("-e"), argv), "--compiled-modules=existing")
    return nothing
end

end
